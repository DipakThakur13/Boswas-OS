def colour(ref: str) -> str:
    scale, _, shade = ref.partition(".")
    value = TOKENS["color"][scale]
    return (value[shade] if shade else value).upper()


def token_palette() -> set[str]:
    out = set()
    for value in TOKENS["color"].values():
        out |= {value.upper()} if isinstance(value, str) else {v.upper() for v in value.values()}
    return out


def mark_colours() -> set[str]:
    """The colours of the Boswas OS mark (its gradient stops and solid fills)."""
    text = (REPO / "desktop/branding/boswas-os-mark.svg").read_text(encoding="utf-8")
    return colours_in(text)


def icon_roles() -> dict:
    """The colour families of the pack: `icon.hues` and `icon.materials`."""
    return {**TOKENS["icon"]["hues"], **TOKENS["icon"]["materials"]}


def luminance(hex_colour: str) -> float:
    def channel(c: float) -> float:
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a: str, b: str) -> float:
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def colours_in(text: str) -> set[str]:
    return {c.upper() for c in re.findall(r"#[0-9A-Fa-f]{6}\b", text)}


def svg_files(root: Path, contexts=COLOURED + SYMBOLIC) -> list[Path]:
    return sorted(p for c in contexts for p in (root / "scalable" / c).glob("*.svg"))


def all_svg_files() -> list[Path]:
    return svg_files(DARK) + svg_files(LIGHT)


def id_prefix(stem: str) -> str:
    return re.sub(r"[^A-Za-z0-9-]", "-", stem) + "-"


def read_theme(path: Path) -> configparser.ConfigParser:
    parser = configparser.ConfigParser(interpolation=None)
    parser.optionxform = str
    parser.read(path, encoding="utf-8")
    return parser


def gradients(root: ET.Element) -> dict:
    """Gradient id -> (element, [(offset, colour, opacity)])."""
    out = {}
    for grad in root.iter():
        if grad.tag in GRADIENTS:
            stops = [(float(st.get("offset")), st.get("stop-color").upper(), float(st.get("stop-opacity", "1")))
                     for st in grad.iter(f"{SVG_NS}stop")]
            out[grad.get("id")] = (grad, stops)
    return out


def shows_mark(stem: str) -> bool:
    return stem in MARK_ICONS


@functools.lru_cache(maxsize=1)
def generator():
    """The generator as a module (for its path geometry: extent())."""
    spec = importlib.util.spec_from_file_location("build_prism", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def drawn_boxes(root: ET.Element) -> tuple[tuple, list[tuple]]:
    """The box of the contact shadow (the first path) and the boxes of every
    other path, strokes included, placed by the transform of their group."""
    extent = generator().extent
    boxes = []

    def walk(el, k=1.0, dx=0.0, dy=0.0):
        for child in el:
            if child.tag == f"{SVG_NS}g":
                m = re.fullmatch(r"translate\(([-\d.]+) ([-\d.]+)\) scale\(([\d.]+)\)", child.get("transform"))
                tx, ty, sk = (float(v) for v in m.groups())
                walk(child, k * sk, dx + k * tx, dy + k * ty)
            elif child.tag == f"{SVG_NS}path":
                x0, y0, x1, y1 = extent(child.get("d"))
                half = float(child.get("stroke-width", "0")) / 2 if child.get("stroke") else 0
                boxes.append((dx + k * (x0 - half), dy + k * (y0 - half), dx + k * (x1 + half), dy + k * (y1 + half)))
    walk(root)
    return boxes[0], boxes[1:]


class SourceTree(unittest.TestCase):
    def test_required_icons_exist(self):
        for context, names in REQUIRED.items():
            for name in names:
                self.assertTrue((DARK / "scalable" / context / f"{name}.svg").is_file(), (context, name))
                if context in SYMBOLIC:
                    self.assertTrue((LIGHT / "scalable" / context / f"{name}.svg").is_file(), (context, name))

    def test_required_names_cover_the_legacy_pack(self):
        legacy = {p.stem for p in (ICONS / "Boswas/scalable/apps").glob("*.svg")} - THIRD_PARTY
        self.assertLessEqual(legacy, {p.stem for p in (DARK / "scalable/apps").glob("*.svg")})
        legacy_mime = {p.stem for p in (ICONS / "Boswas/scalable/mimetypes").glob("*.svg")}
        self.assertLessEqual(legacy_mime, {p.stem for p in (DARK / "scalable/mimetypes").glob("*.svg")})

    def test_only_svg_icons(self):
        for theme in (DARK, LIGHT):
            for path in (theme / "scalable").rglob("*"):
                if path.is_file():
                    self.assertEqual(path.suffix, ".svg", path)
                    self.assertFalse(path.is_symlink(), path)

    def test_theme_directories(self):
        self.assertEqual(sorted(p.name for p in DARK.iterdir()), ["index.theme", "scalable"])
        self.assertEqual(sorted(p.name for p in (DARK / "scalable").iterdir()), sorted(COLOURED + SYMBOLIC))
        # Boswas-Prism-Light gets its coloured icons from install.sh, copied
        # from Boswas-Prism; only its symbolic icons differ and live here.
        self.assertEqual(sorted(p.name for p in LIGHT.iterdir()), ["index.theme", "scalable"])
        self.assertEqual(sorted(p.name for p in (LIGHT / "scalable").iterdir()), sorted(SYMBOLIC))

    def test_readme_lists_every_icon(self):
        readme = (ICONS / "README.md").read_text(encoding="utf-8")
        for path in svg_files(DARK):
            self.assertIn(f"`{path.stem}`", readme, path.stem)
        table = subprocess.run([sys.executable, "-B", str(GENERATOR), "--table"], check=True,
                               capture_output=True, text=True).stdout
        self.assertIn(f"<!-- BEGIN PRISM ICON TABLE -->\n{table}<!-- END PRISM ICON TABLE -->", readme,
                      "README table is stale: paste the output of build_prism.py --table")


class Names(unittest.TestCase):
    """The pack draws Boswas programs and generic names only: every other
    application keeps the icon it installs."""

    def test_no_icon_is_named_after_another_program(self):
        for theme in (DARK, LIGHT):
            for path in svg_files(theme):
                with self.subTest(icon=path.name):
                    self.assertNotIn(path.stem, THIRD_PARTY)
        for path in svg_files(DARK, ("apps",)):
            with self.subTest(icon=path.name):
                # A reverse-DNS desktop file id (org.kde.dolphin) is a program's own name.
                self.assertNotIn(".", path.stem)
                self.assertTrue(path.stem.startswith("boswas-") or path.stem in GENERIC_APPS,
                                "an application icon is a Boswas program or a generic name")

    def test_required_names_are_boswas_or_generic(self):
        self.assertEqual(set(REQUIRED["apps"]) & THIRD_PARTY, set())
        self.assertLessEqual({name for name in REQUIRED["apps"] if not name.startswith("boswas-")}, GENERIC_APPS)


class SvgFiles(unittest.TestCase):
    def test_structure(self):
        files = all_svg_files()
        self.assertGreater(len(files), 280)
        for path in files:
            with self.subTest(icon=path.name):
                text = path.read_text(encoding="utf-8")
                self.assertTrue(text.startswith('<?xml version="1.0" encoding="UTF-8"?>\n'))
                self.assertIn(HEADER, text)
                self.assertNotIn("$", text, "unresolved paint")
                root = ET.fromstring(text)
                self.assertEqual(root.tag, f"{SVG_NS}svg")
                self.assertEqual(root.get("viewBox"), "0 0 256 256")
                self.assertEqual((root.get("width"), root.get("height")), ("256", "256"))
                self.assertIsNotNone(root.find(f"{SVG_NS}title"))

    def test_self_contained_and_qt_safe(self):
        for path in all_svg_files():
            with self.subTest(icon=path.name):
                text = path.read_text(encoding="utf-8")
                root = ET.fromstring(text)
                for el in root.iter():
                    tag = el.tag.replace(SVG_NS, "")
                    self.assertFalse(el is not root and tag in FORBIDDEN_ELEMENTS, tag)
                    self.assertIn(tag, ALLOWED_ELEMENTS)
                    self.assertTrue(el.tag.startswith(SVG_NS), el.tag)
                    for attr, value in el.attrib.items():
                        local = attr.split("}")[-1]
                        self.assertFalse(local.lower().startswith("on"), attr)
                        self.assertNotIn(local, ("style", "class", "filter", "mask", "clip-path"))
                        if local == "href":
                            self.assertTrue(value.startswith("#"), value)
                        for ref in re.findall(r"url\(([^)]*)\)", value):
                            self.assertTrue(ref.startswith("#"), ref)
                for grad in root.iter():
                    if grad.tag in GRADIENTS:
                        # A horizontal or vertical stroke has a bounding box
                        # without area: only user-space gradients paint it.
                        self.assertEqual(grad.get("gradientUnits"), "userSpaceOnUse")
                for word in ("<image", "<script", "<text", "<!entity", "javascript:"):
                    self.assertNotIn(word, text.lower())

    def test_no_teal_and_palette_only(self):
        palette = token_palette()
        mark = mark_colours()
        self.assertTrue(mark)
        for path in all_svg_files():
            with self.subTest(icon=path.name):
                text = path.read_text(encoding="utf-8")
                self.assertIsNone(TEAL.search(text))
                self.assertNotRegex(text, r"rgb\(|hsl\(")
                extra = colours_in(text) - palette
                # Only the Boswas OS mark may bring colours of its own.
                if shows_mark(path.stem):
                    extra -= mark
                self.assertEqual(extra, set())

    def test_ids_unique_prefixed_and_resolved(self):
        for theme in (DARK, LIGHT):
            seen = {}
            for path in svg_files(theme):
                with self.subTest(icon=path.name):
                    text = path.read_text(encoding="utf-8")
                    root = ET.fromstring(text)
                    ids = [el.get("id") for el in root.iter() if el.get("id")]
                    self.assertEqual(len(ids), len(set(ids)), "duplicate id")
                    for ident in ids:
                        self.assertTrue(ident.startswith(id_prefix(path.stem)), ident)
                        # inode-directory (mimetypes) and folder (places) are
                        # different files, so even their ids differ.
                        self.assertNotIn(ident, seen, f"also in {seen.get(ident)}")
                        seen[ident] = path.name
                    refs = set(re.findall(r"url\(#([^)]+)\)", text)) | set(re.findall(r'href="#([^"]+)"', text))
                    self.assertLessEqual(refs, set(ids), refs - set(ids))

    def test_logo_icons_copy_the_mark(self):
        """The mark's paths and gradients are copied, never redrawn; the Start
        button (boswas-logo and its aliases) is the mark alone."""
        mark = ET.parse(REPO / "desktop/branding/boswas-os-mark.svg").getroot()
        paths = [(p.get("fill"), p.get("d")) for p in mark.iter(f"{SVG_NS}path")]
        self.assertGreaterEqual(len(paths), 2)
        mark_grads = gradients(mark)
        for name in MARK_ICONS:
            with self.subTest(icon=name):
                text = (DARK / "scalable/apps" / f"{name}.svg").read_text(encoding="utf-8")
                root = ET.fromstring(text)
                prefix = id_prefix(name)
                drawn = [(p.get("fill"), p.get("d")) for p in root.iter(f"{SVG_NS}path")]
                copied = [(fill.replace("url(#", f"url(#{prefix}"), d) for fill, d in paths]
                for item in copied:
                    self.assertIn(item, drawn)
                grads = gradients(root)
                for ident, (grad, stops) in mark_grads.items():
                    self.assertIn(prefix + ident, grads)
                    mine, my_stops = grads[prefix + ident]
                    self.assertEqual(mine.tag, grad.tag)
