"""Generate the Boswas icon theme.

Every icon is drawn here, on a 256x256 grid, and written as a self-contained
SVG into desktop/icons/Boswas/scalable/{apps,mimetypes}/. The generated files
are committed; re-run this tool after changing a glyph:

    python3 desktop/icons/tools/build_icons.py            # regenerate in place
    python3 desktop/icons/tools/build_icons.py --output DIR
    python3 desktop/icons/tools/build_icons.py --table    # README name table

The official Boswas OS mark is not redrawn: its path data and gradients are
copied from desktop/branding/boswas-os-mark.svg at build time.

Design rules (see desktop/icons/README.md):
  * apps sit on the navy launcher tile of desktop/branding/boswas-mark.svg
    (x=8 y=8 240x240 rx=56, gradient #162034 -> #080C16, thin gold edge);
  * glyphs are line art, stroke 14, round caps and joins, in the silver
    gradient, inside roughly 56..200, with ONE gold accent element;
  * mimetypes are flat light pages with a navy glyph and a gold accent;
  * every id is prefixed with the file's own name, so files can be combined;
  * only features Qt's SVG renderer supports: paths, linear gradients in user
    space, solid fills and strokes. No masks, clip paths, filters, CSS,
    <text>, <image> or nested <svg>.

Python 3 standard library only. Output is deterministic.
"""

