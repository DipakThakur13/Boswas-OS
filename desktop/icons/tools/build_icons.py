# ---------------------------------------------------------------------------
# Number and path helpers
# ---------------------------------------------------------------------------
def n(v: float) -> str:
    """Format a coordinate compactly and deterministically."""
    v = round(v, 2)
    if v == int(v):
        return str(int(v))
    return f"{v:.2f}".rstrip("0").rstrip(".")


def pt(x: float, y: float) -> str:
    return f"{n(x)} {n(y)}"


def polar(cx: float, cy: float, r: float, deg: float) -> tuple[float, float]:
    """Point at clock angle deg (0 = 12 o'clock, clockwise)."""
    a = math.radians(deg)
    return cx + r * math.sin(a), cy - r * math.cos(a)


def line(*pts: tuple[float, float]) -> str:
    return "M" + "L".join(pt(x, y) for x, y in pts)


def poly(*pts: tuple[float, float]) -> str:
    return line(*pts) + "Z"


def rr(x: float, y: float, w: float, h: float, r: float) -> str:
    """Rounded rectangle as path data."""
    return (f"M{pt(x + r, y)}H{n(x + w - r)}A{n(r)} {n(r)} 0 0 1 {pt(x + w, y + r)}"
            f"V{n(y + h - r)}A{n(r)} {n(r)} 0 0 1 {pt(x + w - r, y + h)}"
            f"H{n(x + r)}A{n(r)} {n(r)} 0 0 1 {pt(x, y + h - r)}"
            f"V{n(y + r)}A{n(r)} {n(r)} 0 0 1 {pt(x + r, y)}Z")


def circle(cx: float, cy: float, r: float) -> str:
    return (f"M{pt(cx - r, cy)}A{n(r)} {n(r)} 0 1 0 {pt(cx + r, cy)}"
            f"A{n(r)} {n(r)} 0 1 0 {pt(cx - r, cy)}Z")


def ellipse(cx: float, cy: float, rx: float, ry: float) -> str:
    return (f"M{pt(cx, cy - ry)}A{n(rx)} {n(ry)} 0 1 1 {pt(cx, cy + ry)}"
            f"A{n(rx)} {n(ry)} 0 1 1 {pt(cx, cy - ry)}Z")


def arc(cx: float, cy: float, r: float, a0: float, a1: float) -> str:
    """Clockwise arc from clock angle a0 to a1 (degrees)."""
    sweep = (a1 - a0) % 360 or 360
    x0, y0 = polar(cx, cy, r, a0)
    x1, y1 = polar(cx, cy, r, a1)
    large = 1 if sweep > 180 else 0
    return f"M{pt(x0, y0)}A{n(r)} {n(r)} 0 {large} 1 {pt(x1, y1)}"


def arc_tangent(deg: float) -> tuple[float, float]:
    """Direction of travel of a clockwise arc at clock angle deg."""
    a = math.radians(deg)
    return math.cos(a), math.sin(a)


def arrowhead(tip: tuple[float, float], direction: tuple[float, float],
              size: float = 22, spread: float = 42) -> str:
    """Open chevron at tip, pointing along direction."""
    dx, dy = direction
    length = math.hypot(dx, dy)
    dx, dy = dx / length, dy / length
    ends = []
    for s in (spread, -spread):
        a = math.radians(s)
        bx = -dx * math.cos(a) + dy * math.sin(a)
        by = -dx * math.sin(a) - dy * math.cos(a)
        ends.append((tip[0] + bx * size, tip[1] + by * size))
    return line(ends[0], tip, ends[1])


def gear(cx: float, cy: float, teeth: int, r_out: float, r_in: float,
         top: float, base: float, phase: float = 0) -> str:
    """Gear outline: trapezoid teeth joined by root arcs (angles in degrees)."""
    pitch = 360 / teeth
    d = []
    for i in range(teeth):
        a = phase + i * pitch
        p1 = polar(cx, cy, r_in, a - base)
        p2 = polar(cx, cy, r_out, a - top)
        p3 = polar(cx, cy, r_out, a + top)
        p4 = polar(cx, cy, r_in, a + base)
        nxt = polar(cx, cy, r_in, a + pitch - base)
        if i == 0:
            d.append("M" + pt(*p1))
        d.append(f"L{pt(*p2)}L{pt(*p3)}L{pt(*p4)}A{n(r_in)} {n(r_in)} 0 0 1 {pt(*nxt)}")
    return "".join(d) + "Z"


def shield(cx: float, top: float, half: float, height: float) -> str:
    """Heater shield: flat shoulders, curved sides meeting in a point."""
    y1 = top + height * 0.16
    mid = top + height * 0.52
    bottom = top + height
    return (f"M{pt(cx, top)}L{pt(cx + half, y1)}V{n(mid)}"
            f"Q{pt(cx + half, bottom - height * 0.14)} {pt(cx, bottom)}"
            f"Q{pt(cx - half, bottom - height * 0.14)} {pt(cx - half, mid)}"
            f"V{n(y1)}Z")


def pencil(tail: tuple[float, float], tip: tuple[float, float], width: float = 24,
           point: float = 26) -> str:
    """Pencil silhouette (body plus sharpened point) from tail to tip."""
    tx, ty = tail
    px, py = tip
    length = math.hypot(px - tx, py - ty)
    ux, uy = (px - tx) / length, (py - ty) / length
    nx, ny = -uy * width / 2, ux * width / 2
    bx, by = px - ux * point, py - uy * point
    return poly((tx + nx, ty + ny), (bx + nx, by + ny), (px, py),
                (bx - nx, by - ny), (tx - nx, ty - ny))


# ---------------------------------------------------------------------------
# Element helpers. A paint is a "$name" token for a gradient (resolved per
# file into url(#<file>-<name>)) or a plain hex colour.
# ---------------------------------------------------------------------------
SILVER = "$silver"
GOLD = "$gold"
TILE = "$tile"
PAGE_PAINT = "$page"
INK = NAVY_800  # glyph colour on the light mimetype page


def stroke(d: str, paint: str = SILVER, w: float = W) -> str:
    return (f'<path d="{d}" fill="none" stroke="{paint}" stroke-width="{n(w)}" '
            f'stroke-linecap="round" stroke-linejoin="round"/>')


def fill(d: str, paint: str = SILVER) -> str:
    return f'<path d="{d}" fill="{paint}"/>'


def solid(d: str, paint: str = GOLD, w: float = 6) -> str:
    """Filled shape with a thin stroke of the same paint (softened corners)."""
    return (f'<path d="{d}" fill="{paint}" stroke="{paint}" stroke-width="{n(w)}" '
            f'stroke-linecap="round" stroke-linejoin="round"/>')


def knock(d: str, w: float = 2 * W, paint: str = TILE) -> str:
    """Halo in the background paint, so an accent stands clear of lines below.

    The background gradients are opaque and in user space, so the halo is
    invisible against the tile (or page) and only interrupts the lines."""
    return solid(d, paint, w)


# ---------------------------------------------------------------------------
# The traced Boswas OS mark, copied from desktop/branding
# ---------------------------------------------------------------------------
_MARK: dict = {}


def load_mark() -> dict:
    if _MARK:
        return _MARK
    root = ET.parse(BRANDING / "boswas-os-mark.svg").getroot()
    gradients = {}
    for grad in root.iter(f"{{{SVG_NS}}}linearGradient"):
        attrs = {k: grad.get(k) for k in ("gradientUnits", "x1", "y1", "x2", "y2") if grad.get(k)}
        stops = [(s.get("offset"), s.get("stop-color"), 1) for s in grad.iter(f"{{{SVG_NS}}}stop")]
        gradients[grad.get("id")] = (attrs, stops)
    groups = []
    for g in root.findall(f"{{{SVG_NS}}}g"):
        groups.append((g.get("transform"),
                       [(p.get("fill"), p.get("d")) for p in g.findall(f"{{{SVG_NS}}}path")]))
    _MARK.update(viewbox=[float(v) for v in root.get("viewBox").split()],
                 gradients=gradients, groups=groups)
    return _MARK


def mark(x: float, y: float, w: float, h: float) -> str:
    """The full-colour mark fitted (centred, aspect kept) into a box."""
    data = load_mark()
    vx, vy, vw, vh = data["viewbox"]
    s = min(w / vw, h / vh)
    dx = x + (w - vw * s) / 2 - vx * s
    dy = y + (h - vh * s) / 2 - vy * s
    tokens = {f"url(#{source})": f"${name}" for name, source in MARK_GRADIENTS.items()}
    out = [f'<g transform="translate({dx:.3f} {dy:.3f}) scale({s:.6f})">']
    for transform, paths in data["groups"]:
        out.append(f'<g transform="{transform}">')
        for paint, d in paths:
            out.append(f'<path fill="{tokens.get(paint, paint)}" d="{d}"/>')
        out.append("</g>")
    out.append("</g>")
    return "\n".join(out)


