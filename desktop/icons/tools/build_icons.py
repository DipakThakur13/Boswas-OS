def id_prefix(file_name: str) -> str:
    """Id prefix for a file: its name with anything but [A-Za-z0-9-] as '-'."""
    return re.sub(r"[^A-Za-z0-9-]", "-", file_name)


def gradient_def(prefix: str, name: str) -> str:
    if name in MARK_GRADIENTS:
        attrs, stops = load_mark()["gradients"][MARK_GRADIENTS[name]]
    else:
        attrs, stops = GRADIENTS[name]
        attrs = dict(attrs, gradientUnits="userSpaceOnUse")
    attr_text = " ".join(f'{k}="{v}"' for k, v in sorted(attrs.items()))
    out = [f'    <linearGradient id="{prefix}-{name}" {attr_text}>']
    for offset, colour, opacity in stops:
        op = f' stop-opacity="{opacity}"' if opacity != 1 else ""
        out.append(f'      <stop offset="{offset}" stop-color="{colour}"{op}/>')
    out.append("    </linearGradient>")
    return "\n".join(out)


def background(kind: str) -> list[str]:
    if kind == APPS:
        return ['<rect x="8" y="8" width="240" height="240" rx="56" ry="56" fill="$tile"/>',
                '<rect x="9.5" y="9.5" width="237" height="237" rx="54.5" ry="54.5" '
                'fill="none" stroke="$edge" stroke-width="3"/>']
    return [f'<path d="{PAGE}" fill="$page" stroke="#3C485C" stroke-opacity="0.45" stroke-width="3"/>',
            f'<path d="{FOLD}" fill="$fold"/>']


def render(file_name: str, title: str, glyph, kind: str) -> str:
    prefix = id_prefix(file_name)
    body = "\n".join("  " + text for el in background(kind) + glyph() for text in el.split("\n"))
    order = list(GRADIENTS) + list(MARK_GRADIENTS)
    used = sorted(set(re.findall(r"\$([a-z]+)", body)), key=order.index)
    body = re.sub(r"\$([a-z]+)", lambda m: f"url(#{prefix}-{m.group(1)})", body)
    defs = "\n".join(gradient_def(prefix, name) for name in used)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">\n'
            f"  <title>{title}</title>\n"
            f"  <!-- {HEADER} -->\n"
            f"  <defs>\n{defs}\n  </defs>\n"
            f"{body}\n"
            "</svg>\n")


def all_files():
    """Yield (context, file name, design name, title, glyph) for every file."""
    for name, title, glyph, kind, aliases in ICONS:
        for file_name in (name,) + tuple(aliases):
            yield kind, file_name, name, title, glyph


def build(output: Path) -> list[Path]:
    """Write every icon under output/scalable/; remove stale SVGs there."""
    written = []
    for kind, file_name, _design, title, glyph in all_files():
        target = output / "scalable" / kind / f"{file_name}.svg"
        target.parent.mkdir(parents=True, exist_ok=True)
        data = render(file_name, title, glyph, kind).encode("utf-8")
        if not target.exists() or target.read_bytes() != data:
            target.write_bytes(data)
        written.append(target)
    keep = set(written)
    for kind in (APPS, MIME):
        for stale in sorted((output / "scalable" / kind).glob("*.svg")):
            if stale not in keep:
                stale.unlink()
    return written


def table() -> str:
    """Markdown table of every design, its glyph and its theme names."""
    rows = ["| Design | Glyph | Theme icon names |", "|---|---|---|"]
    for name, title, glyph, kind, aliases in ICONS:
        names = ", ".join(f"`{x}`" for x in (name,) + tuple(aliases))
        where = " (mimetype)" if kind == MIME else ""
        rows.append(f"| {title}{where} | {glyph.__doc__.strip()} | {names} |")
    return "\n".join(rows)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Generate the Boswas icon theme.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="theme directory to write (default: desktop/icons/Boswas)")
    parser.add_argument("--table", action="store_true", help="print the README name table")
    args = parser.parse_args(argv)
    if args.table:
        print(table())
        return 0
    files = build(args.output)
    print(f"{len(ICONS)} designs, {len(files)} files written to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
