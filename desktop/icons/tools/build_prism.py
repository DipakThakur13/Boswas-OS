# ---------------------------------------------------------------------------
# Tokens (desktop/ui/tokens.json)
# ---------------------------------------------------------------------------
_TOKENS: dict = {}


def tokens() -> dict:
    if not _TOKENS:
        _TOKENS.update(json.loads(TOKENS_FILE.read_text(encoding="utf-8")))
    return _TOKENS


def colour(ref: str) -> str:
    """Resolve a palette reference ("iris.500", "white") to its hex value."""
    scale, _, shade = ref.partition(".")
    value = tokens()["color"][scale]
    return (value[shade] if shade else value).upper()


def family(name: str) -> dict:
    """The colour roles of a hue or material of the pack (token references)."""
    icon = tokens()["icon"]
    return icon["hues"][name] if name in icon["hues"] else icon["materials"][name]


def light(key: str):
    """A value of the pack's light: highlight, shade and contact shadow."""
    return tokens()["icon"]["light"][key]


# ---------------------------------------------------------------------------
# Numbers and path data
# ---------------------------------------------------------------------------
def n(v: float) -> str:
    """Format a coordinate compactly and deterministically."""
    v = round(v, 2)
    if v == int(v):
        return str(int(v))
    return f"{v:.2f}".rstrip("0").rstrip(".")


def pt(x: float, y: float) -> str:
    return f"{n(x)} {n(y)}"


def polar(cx: float, cy: float, r: float, deg: float) -> tuple[float, float]:
    """Point at clock angle deg (0 = 12 o'clock, clockwise)."""
    a = math.radians(deg)
    return cx + r * math.sin(a), cy - r * math.cos(a)


def line(*pts: tuple[float, float]) -> str:
    return "M" + "L".join(pt(x, y) for x, y in pts)


def poly(*pts: tuple[float, float]) -> str:
    return line(*pts) + "Z"


def rr(x: float, y: float, w: float, h: float, r: float) -> str:
    """Rounded rectangle, clockwise."""
    r = min(r, w / 2, h / 2)
    return (f"M{pt(x + r, y)}H{n(x + w - r)}A{n(r)} {n(r)} 0 0 1 {pt(x + w, y + r)}"
            f"V{n(y + h - r)}A{n(r)} {n(r)} 0 0 1 {pt(x + w - r, y + h)}"
            f"H{n(x + r)}A{n(r)} {n(r)} 0 0 1 {pt(x, y + h - r)}"
            f"V{n(y + r)}A{n(r)} {n(r)} 0 0 1 {pt(x + r, y)}Z")


def rrect(x: float, y: float, w: float, h: float, top: float, bottom: float) -> str:
    """Rectangle with one radius for the top corners and one for the bottom ones."""
    path = f"M{pt(x + top, y)}H{n(x + w - top)}"
    path += f"A{n(top)} {n(top)} 0 0 1 {pt(x + w, y + top)}" if top else ""
    path += f"V{n(y + h - bottom)}"
    path += f"A{n(bottom)} {n(bottom)} 0 0 1 {pt(x + w - bottom, y + h)}" if bottom else ""
    path += f"H{n(x + bottom)}"
    path += f"A{n(bottom)} {n(bottom)} 0 0 1 {pt(x, y + h - bottom)}" if bottom else ""
    path += f"V{n(y + top)}"
    path += f"A{n(top)} {n(top)} 0 0 1 {pt(x + top, y)}" if top else ""
    return path + "Z"


def circle(cx: float, cy: float, r: float) -> str:
    """Circle, clockwise (so that it unites with rr() parts of one path)."""
    return (f"M{pt(cx - r, cy)}A{n(r)} {n(r)} 0 1 1 {pt(cx + r, cy)}"
            f"A{n(r)} {n(r)} 0 1 1 {pt(cx - r, cy)}Z")


def ellipse(cx: float, cy: float, rx: float, ry: float) -> str:
    return (f"M{pt(cx - rx, cy)}A{n(rx)} {n(ry)} 0 1 1 {pt(cx + rx, cy)}"
            f"A{n(rx)} {n(ry)} 0 1 1 {pt(cx - rx, cy)}Z")


def arc(cx: float, cy: float, r: float, a0: float, a1: float) -> str:
    """Clockwise arc from clock angle a0 to a1 (degrees)."""
    sweep = (a1 - a0) % 360 or 360
    x0, y0 = polar(cx, cy, r, a0)
    x1, y1 = polar(cx, cy, r, a1)
    return f"M{pt(x0, y0)}A{n(r)} {n(r)} 0 {1 if sweep > 180 else 0} 1 {pt(x1, y1)}"


def arc_tangent(deg: float) -> tuple[float, float]:
    """Direction of travel of a clockwise arc at clock angle deg."""
    a = math.radians(deg)
    return math.cos(a), math.sin(a)


def arrowhead(tip: tuple[float, float], direction: tuple[float, float],
              size: float = 22, spread: float = 42) -> str:
    """Open chevron at tip, pointing along direction."""
    dx, dy = direction
    length = math.hypot(dx, dy)
    dx, dy = dx / length, dy / length
    ends = []
    for s in (spread, -spread):
        a = math.radians(s)
        bx = -dx * math.cos(a) + dy * math.sin(a)
        by = -dx * math.sin(a) - dy * math.cos(a)
        ends.append((tip[0] + bx * size, tip[1] + by * size))
    return line(ends[0], tip, ends[1])


def gear(cx: float, cy: float, teeth: int, r_out: float, r_in: float,
         top: float, base: float, phase: float = 0) -> str:
    """Gear outline: trapezoid teeth joined by root arcs (angles in degrees)."""
    pitch = 360 / teeth
    d = []
    for i in range(teeth):
        a = phase + i * pitch
        p1 = polar(cx, cy, r_in, a - base)
        p2 = polar(cx, cy, r_out, a - top)
        p3 = polar(cx, cy, r_out, a + top)
        p4 = polar(cx, cy, r_in, a + base)
        nxt = polar(cx, cy, r_in, a + pitch - base)
        if i == 0:
            d.append("M" + pt(*p1))
        d.append(f"L{pt(*p2)}L{pt(*p3)}L{pt(*p4)}A{n(r_in)} {n(r_in)} 0 0 1 {pt(*nxt)}")
    return "".join(d) + "Z"


def shield(cx: float, top: float, half: float, height: float) -> str:
    """Shield: rounded shoulders, curved sides meeting in a point."""
    y1 = top + height * 0.14
    mid = top + height * 0.5
    bottom = top + height
    k = half * 0.18
    return (f"M{pt(cx, top)}Q{pt(cx + half * 0.5, y1 - height * 0.02)} {pt(cx + half - k, y1)}"
            f"Q{pt(cx + half, y1)} {pt(cx + half, y1 + k)}V{n(mid)}"
            f"Q{pt(cx + half, bottom - height * 0.16)} {pt(cx, bottom)}"
            f"Q{pt(cx - half, bottom - height * 0.16)} {pt(cx - half, mid)}"
            f"V{n(y1 + k)}Q{pt(cx - half, y1)} {pt(cx - half + k, y1)}"
            f"Q{pt(cx - half * 0.5, y1 - height * 0.02)} {pt(cx, top)}Z")


def crescent(cx: float, cy: float, radius: float, dx: float, dy: float, cut: float) -> str:
    """Moon: the disc (cx, cy, radius) minus the disc (cx + dx, cy + dy, cut)."""
    d = math.hypot(dx, dy)
    along = (radius * radius - cut * cut + d * d) / (2 * d)
    across = math.sqrt(radius * radius - along * along)
    mx, my = cx + along * dx / d, cy + along * dy / d
    p1 = (mx + across * dy / d, my - across * dx / d)
    p2 = (mx - across * dy / d, my + across * dx / d)
    a1, a2, ac = (math.atan2(y - cy, x - cx) for x, y in (p1, p2, (cx + dx, cy + dy)))
    sweep = 0 if (ac - a1) % math.tau < (a2 - a1) % math.tau else 1
    extent = (a2 - a1) % math.tau if sweep else (a1 - a2) % math.tau
    return (f"M{pt(*p1)}A{n(radius)} {n(radius)} 0 {1 if extent > math.pi else 0} {sweep} {pt(*p2)}"
            f"A{n(cut)} {n(cut)} 0 {1 if along > d else 0} {1 - sweep} {pt(*p1)}Z")


def cloud_path(cx: float, base: float, scale: float = 1.0, round_base: float = 0.0) -> str:
    """Outline of a cloud: three bumps (left, top, right) on a base line,
    centred on cx. At scale 1 it is 172 wide and 124 high. round_base > 0
    rounds the two bottom corners with that radius (a solid cloud)."""
    bumps = [(-44, -34, 34), (4, -74, 50), (58, -38, 36)]
    circles = [(cx + dx * scale, base + dy * scale, r * scale) for dx, dy, r in bumps]

    def meet(a, b):
        (x0, y0, r0), (x1, y1, r1) = a, b
        d = math.hypot(x1 - x0, y1 - y0)
        along = (r0 * r0 - r1 * r1 + d * d) / (2 * d)
        h = math.sqrt(max(r0 * r0 - along * along, 0.0))
        mx, my = x0 + along * (x1 - x0) / d, y0 + along * (y1 - y0) / d
        p = (mx + h * (y1 - y0) / d, my - h * (x1 - x0) / d)
        q = (mx - h * (y1 - y0) / d, my + h * (x1 - x0) / d)
        return p if p[1] < q[1] else q

    (lx, _ly, lr), (_tx, _ty, tr), (rx, _ry, rrad) = circles
    a = meet(circles[0], circles[1])
    b = meet(circles[1], circles[2])
    return (f"M{pt(lx, base)}A{n(lr)} {n(lr)} 0 0 1 {pt(*a)}"
            f"A{n(tr)} {n(tr)} 0 0 1 {pt(*b)}"
            f"A{n(rrad)} {n(rrad)} 0 0 1 {pt(rx, base)}Z")


def star(cx: float = 128, cy: float = 136, outer: float = 104, inner: float = 44) -> str:
    return poly(*[polar(cx, cy, outer if i % 2 == 0 else inner, i * 36) for i in range(10)])


# Path data parsing: the helpers above write absolute commands only.
_PATH_TOKEN = re.compile(r"[MLHVCSQTAZ]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")
_ARGS = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "T": 2, "A": 7, "Z": 0}


def parse_path(d: str) -> list[tuple[str, list[float]]]:
    if re.search(r"[a-z]", d):
        raise ValueError(f"relative path commands are not supported here: {d[:40]}")
    out, cmd = [], None
    tokens_ = _PATH_TOKEN.findall(d)
    i = 0
    while i < len(tokens_):
        if tokens_[i] in _ARGS:
            cmd = tokens_[i]
            i += 1
            if cmd == "Z":
                out.append(("Z", []))
                continue
        count = _ARGS[cmd]
        out.append((cmd, [float(v) for v in tokens_[i:i + count]]))
        i += count
        if cmd == "M":
            cmd = "L"
    return out


def unparse_path(segments) -> str:
    out = []
    for cmd, args in segments:
        if cmd == "A":
            rx, ry, rot, large, sweep, x, y = args
            out.append(f"A{n(rx)} {n(ry)} {n(rot)} {int(large)} {int(sweep)} {pt(x, y)}")
        else:
            out.append(cmd + " ".join(n(v) for v in args))
    return "".join(out)


def move(d: str, dx: float, dy: float) -> str:
    """The path translated by (dx, dy)."""
    out = []
    for cmd, args in parse_path(d):
        if cmd == "H":
            args = [args[0] + dx]
        elif cmd == "V":
            args = [args[0] + dy]
        elif cmd == "A":
            args = args[:5] + [args[5] + dx, args[6] + dy]
        else:
            args = [v + (dx if i % 2 == 0 else dy) for i, v in enumerate(args)]
        out.append((cmd, args))
    return unparse_path(out)


def _arc_points(x0, y0, rx, ry, rot, large, sweep, x1, y1, steps=24):
    """Points along an SVG arc (endpoint parametrisation), for bounding boxes."""
    if rx == 0 or ry == 0 or (x0, y0) == (x1, y1):
        return [(x1, y1)]
    phi = math.radians(rot)
    c, s = math.cos(phi), math.sin(phi)
    dx, dy = (x0 - x1) / 2, (y0 - y1) / 2
    x1p, y1p = c * dx + s * dy, -s * dx + c * dy
    lam = (x1p / rx) ** 2 + (y1p / ry) ** 2
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx * rx * ry * ry - rx * rx * y1p * y1p - ry * ry * x1p * x1p
    den = rx * rx * y1p * y1p + ry * ry * x1p * x1p
    k = math.sqrt(max(num / den, 0)) * (-1 if large == sweep else 1)
    cxp, cyp = k * rx * y1p / ry, -k * ry * x1p / rx
    cx, cy = c * cxp - s * cyp + (x0 + x1) / 2, s * cxp + c * cyp + (y0 + y1) / 2

    def angle(ux, uy, vx, vy):
        return math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)
    t0 = angle(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry)
    dt = angle((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry)
    if not sweep and dt > 0:
        dt -= math.tau
    elif sweep and dt < 0:
        dt += math.tau
    pts = []
    for i in range(1, steps + 1):
        t = t0 + dt * i / steps
        ex, ey = rx * math.cos(t), ry * math.sin(t)
        pts.append((cx + c * ex - s * ey, cy + s * ex + c * ey))
    return pts


def bbox(d: str) -> tuple[float, float, float, float]:
    """Bounding box of a path (control points included: a little generous)."""
    xs, ys = [], []
    x = y = 0.0
    for cmd, args in parse_path(d):
        if cmd == "H":
            x = args[0]
        elif cmd == "V":
            y = args[0]
        elif cmd == "A":
            for px, py in _arc_points(x, y, *args):
                xs.append(px)
                ys.append(py)
            x, y = args[5], args[6]
        elif cmd != "Z":
            xs += args[0::2]
            ys += args[1::2]
            x, y = args[-2], args[-1]
            continue
        else:
            continue
        xs.append(x)
        ys.append(y)
    return min(xs), min(ys), max(xs), max(ys)


