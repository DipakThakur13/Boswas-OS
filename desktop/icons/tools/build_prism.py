_TOKENS: dict = {}


def tokens() -> dict:
    if not _TOKENS:
        _TOKENS.update(json.loads(TOKENS_FILE.read_text(encoding="utf-8")))
    return _TOKENS


def colour(ref: str) -> str:
    """Resolve a token reference ("iris.500", "white") to its hex value."""
    scale, _, shade = ref.partition(".")
    value = tokens()["color"][scale]
    return (value[shade] if shade else value).upper()


def luminance(hex_colour: str) -> float:
    def channel(c: float) -> float:
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a: str, b: str) -> float:
    """WCAG contrast ratio of two hex colours."""
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def _step(ref: str, away_from_light: bool) -> str:
    """The next darker (or lighter) shade of the same scale."""
    scale, _, shade = ref.partition(".")
    shades = sorted(int(s) for s in tokens()["color"][scale])
    i = shades.index(int(shade)) + (1 if away_from_light else -1)
    if not 0 <= i < len(shades):
        raise SystemExit(f"build_prism: no shade of {scale} gives the glyph enough contrast")
    return f"{scale}.{shades[i]}"


_HUES: dict = {}


def hue(name: str) -> dict:
    """The resolved colours of one icon hue: from, to, glyph, accent, onaccent.

    Contrast guard: a tile stop that gives the glyph less than GLYPH_MIN
    contrast moves to the next shade of its own scale (darker for a light
    glyph). With the current tokens this only moves sky.500 (2.998:1 against
    white) to sky.600."""
    if name not in _HUES:
        spec = tokens()["icon"]["hues"][name]
        glyph = colour(spec["glyph"])
        light_glyph = luminance(glyph) > 0.5
        stops = {}
        for key in ("from", "to"):
            ref = spec[key]
            while contrast(glyph, colour(ref)) < GLYPH_MIN:
                ref = _step(ref, light_glyph)
            stops[key] = colour(ref)
        accent = colour(spec["accent"])
        ink, white = colour("ink.900"), colour("white")
        _HUES[name] = dict(stops, glyph=glyph, accent=accent,
                           onaccent=max((ink, white), key=lambda c: contrast(c, accent)))
    return _HUES[name]


