#!/usr/bin/env python3
"""Generate the Boswas Prism icon themes.

Boswas Prism is the icon pack of the native Boswas desktop. Every icon is
drawn here, on a 256x256 grid, and written as a self-contained SVG into

    desktop/icons/Boswas-Prism/scalable/{apps,places,devices,mimetypes,status,actions}/
    desktop/icons/Boswas-Prism-Light/scalable/{status,actions}/

The generated files are committed; re-run this tool after changing a drawing,
desktop/ui/tokens.json or the Boswas OS mark:

    python3 desktop/icons/tools/build_prism.py            # regenerate in place
    python3 desktop/icons/tools/build_prism.py --output DIR   # DIR/Boswas-Prism, DIR/Boswas-Prism-Light
    python3 desktop/icons/tools/build_prism.py --table    # README name table

Design rules (see desktop/icons/README.md):
  * every colour comes from desktop/ui/tokens.json: the palette (`color`)
    and the colour roles of the pack (`icon`). The Boswas OS mark keeps its
    own colours: its paths and gradients are copied from
    desktop/branding/boswas-os-mark.svg, never redrawn;
  * coloured icons (applications, places, devices, mimetypes) are objects
    without a tile: soft linear gradients lit from the top, layered parts
    with a subtle shade where they overlap, a highlight along top edges, a
    soft contact shadow under the object and one corner radius per size of
    part;
  * status and action icons are symbolic line icons: one flat colour,
    strokes of 16 units with round caps and joins, written twice (cloud.50
    for dark panels, ink.900 for light panels);
  * only features Qt's SVG renderer, resvg and librsvg all support: paths,
    groups, linear and radial gradients in user space, solid fills and
    strokes, opacity and fill-rule. No masks, clip paths, filters, CSS,
    <text>, <image>, <use> or nested <svg>. Every id is prefixed with the
    file's own name.

Python 3 standard library only. Output is deterministic.
"""

