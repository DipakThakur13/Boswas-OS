# The mark's own gradients, copied from the traced mark by the legacy loader.
MARK_GRADIENTS = legacy.MARK_GRADIENTS
# Shade of the hue used for line art on the light page (>= 4:1 on white).
STRONG = {"sun": "700", "slate": "500", "mint": "600", "sky": "600"}
TOKEN_RE = re.compile(r"\$([a-z][a-z0-9-]*)")


def solid_paint(name: str, hue_name: str, sym: str | None) -> str | None:
    """Hex colour of a solid paint name, or None when it names a gradient."""
    if name in GRADIENTS or name in MARK_GRADIENTS:
        return None
    if name == "sym":
        return colour(sym)
    if name in ("glyph", "accent", "onaccent", "from", "to"):
        return hue(hue_name)[name]
    if name == "strong":
        return colour(f"{hue_name}.{STRONG.get(hue_name, '600')}")
    if re.fullmatch(r"c[0-9]{3}", name):
        return colour(f"{hue_name}.{name[1:]}")
    scale, _, shade = name.partition("-")
    return colour(f"{scale}.{shade}" if shade else scale)


def gradient_def(prefix: str, name: str, hue_name: str) -> str:
    if name in MARK_GRADIENTS:
        attrs, stops = legacy.load_mark()["gradients"][MARK_GRADIENTS[name]]
        stops = [(offset, stop, 1) for offset, stop, _ in stops]
    else:
        x1, y1, x2, y2, spec = GRADIENTS[name]
        attrs = {"gradientUnits": "userSpaceOnUse", "x1": n(x1), "y1": n(y1), "x2": n(x2), "y2": n(y2)}
        stops = [(n(offset), solid_paint(paint, hue_name, None), opacity) for offset, paint, opacity in spec]
    attr_text = " ".join(f'{k}="{v}"' for k, v in sorted(attrs.items()))
    out = [f'    <linearGradient id="{prefix}-{name}" {attr_text}>']
    for offset, stop, opacity in stops:
        op = f' stop-opacity="{n(opacity)}"' if opacity != 1 else ""
        out.append(f'      <stop offset="{offset}" stop-color="{stop}"{op}/>')
    out.append("    </linearGradient>")
    return "\n".join(out)


