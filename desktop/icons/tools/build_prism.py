SW = 22     # stroke width: 1.4 px at 16 px
DIM = 0.35


def y_s(d: str, w: float = SW, dim: bool = False) -> str:
    return S(d, "$sym", w, DIM if dim else None)


def y_f(d: str, dim: bool = False, evenodd: bool = False) -> str:
    return F(d, "$sym", DIM if dim else None, evenodd)


def y_fs(d: str, w: float = 12, dim: bool = False, evenodd: bool = False) -> str:
    return FS(d, "$sym", w, DIM if dim else None, evenodd)


