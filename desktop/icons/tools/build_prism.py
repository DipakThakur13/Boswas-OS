def id_prefix(file_name: str) -> str:
    """Id prefix for a file: its name with anything but [A-Za-z0-9-] as '-'."""
    return re.sub(r"[^A-Za-z0-9-]", "-", file_name)


def on_tile(elements: list[str], hue_name: str) -> list[str]:
    """Tile, glyph and the top highlight.

    The highlight goes above the last knock-out (an element in the tile
    paint), so a knock-out stays invisible against the lit tile; a light
    glyph below it is not changed by a white highlight. The official mark is
    never tinted: on its ink tile the highlight stays directly on the tile."""
    last = max((i for i, el in enumerate(elements) if "$tile" in el), default=-1)
    at = 0 if hue_name == "ink" else last + 1
    shine = F(TILE_D, "$shine")
    return [F(TILE_D, "$tile")] + elements[:at] + [shine] + elements[at:]


def render(context: str, file_name: str, title: str, glyph, hue_name: str | None, sym: str | None) -> str:
    prefix = id_prefix(file_name)
    elements = glyph()
    if context == APPS:
        elements = on_tile(elements, hue_name)
    body = "\n".join("  " + text for el in elements for text in el.split("\n"))
    order = list(GRADIENTS) + list(MARK_GRADIENTS)
    used: set[str] = set()

    def paint(match: re.Match) -> str:
        name = match.group(1)
        value = solid_paint(name, hue_name, sym)
        if value is not None:
            return value
        used.add(name)
        return f"url(#{prefix}-{name})"

    body = TOKEN_RE.sub(paint, body)
    defs = "\n".join(gradient_def(prefix, name, hue_name) for name in sorted(used, key=order.index))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">\n'
            f"  <title>{title}</title>\n"
            f"  <!-- {HEADER} -->\n"
            + (f"  <defs>\n{defs}\n  </defs>\n" if defs else "") +
            f"{body}\n"
            "</svg>\n")


def all_files():
    """Yield (theme, context, file name, design name, title, glyph, hue) for every file."""
    for context, name, title, glyph, aliases, hue_name in icons():
        for theme in (DARK, LIGHT) if context in SYMBOLIC else (DARK,):
            for file_name in (name,) + tuple(aliases):
                yield theme, context, file_name, name, title, glyph, hue_name


def build(output: Path) -> list[Path]:
    """Write every icon under output/<theme>/scalable/; remove stale SVGs there."""
    written = []
    for theme, context, file_name, _design, title, glyph, hue_name in all_files():
        target = output / theme / "scalable" / context / f"{file_name}.svg"
        target.parent.mkdir(parents=True, exist_ok=True)
        sym = SYMBOLIC_INK[theme] if context in SYMBOLIC else None
        data = render(context, file_name, title, glyph, hue_name, sym).encode("utf-8")
        if not target.exists() or target.read_bytes() != data:
            target.write_bytes(data)
        written.append(target)
    keep = set(written)
    for theme in (DARK, LIGHT):
        for stale in sorted((output / theme / "scalable").glob("*/*.svg")):
            if stale not in keep:
                stale.unlink()
    return written


def table() -> str:
    """Markdown table of every design, its hue, its glyph and its theme names."""
    rows = ["| Context | Design | Hue | Glyph | Theme icon names |", "|---|---|---|---|---|"]
    for context, name, title, glyph, aliases, hue_name in icons():
        names = ", ".join(f"`{x}`" for x in (name,) + tuple(aliases))
        rows.append(f"| {context} | {title} | {hue_name or 'symbolic'} | {glyph.__doc__.strip()} | {names} |")
    return "\n".join(rows)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Generate the Boswas Prism icon themes.")
    parser.add_argument("--output", type=Path, default=ICONS_DIR,
                        help="directory that holds Boswas-Prism/ and Boswas-Prism-Light/ (default: desktop/icons)")
    parser.add_argument("--table", action="store_true", help="print the README name table")
    args = parser.parse_args(argv)
    if args.table:
        print(table())
        return 0
    files = build(args.output)
    print(f"{len(icons())} designs, {len(files)} files written to {args.output}/{DARK} and {args.output}/{LIGHT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
