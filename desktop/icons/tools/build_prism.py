class Grad:
    """A gradient in user space. Stops are (offset, palette reference, opacity)."""

    def __init__(self, kind: str, name: str, geometry: tuple, stops: list[tuple]):
        self.kind, self.name, self.geometry = kind, name, tuple(round(v, 2) for v in geometry)
        self.stops = tuple((round(o, 3), ref, round(op, 3)) for o, ref, op in stops)
        self.key = (kind, self.geometry, self.stops)

    def svg(self, ident: str) -> str:
        if self.kind == "linear":
            x1, y1, x2, y2 = self.geometry
            head = (f'<linearGradient id="{ident}" gradientUnits="userSpaceOnUse" '
                    f'x1="{n(x1)}" y1="{n(y1)}" x2="{n(x2)}" y2="{n(y2)}">')
            tail = "</linearGradient>"
        else:
            cx, cy, rx, ry = self.geometry
            head = (f'<radialGradient id="{ident}" gradientUnits="userSpaceOnUse" cx="0" cy="0" r="1" '
                    f'gradientTransform="translate({n(cx)} {n(cy)}) scale({n(rx)} {n(ry)})">')
            tail = "</radialGradient>"
        out = ["    " + head]
        for offset, ref, opacity in self.stops:
            op = f' stop-opacity="{n(opacity)}"' if opacity != 1 else ""
            out.append(f'      <stop offset="{n(offset)}" stop-color="{colour(ref)}"{op}/>')
        out.append("    " + tail)
        return "\n".join(out)


def lin(name: str, x1: float, y1: float, x2: float, y2: float, *stops) -> Grad:
    return Grad("linear", name, (x1, y1, x2, y2), [s if len(s) == 3 else (*s, 1) for s in stops])


def rad(name: str, cx: float, cy: float, rx: float, ry: float, *stops) -> Grad:
    return Grad("radial", name, (cx, cy, rx, ry), [s if len(s) == 3 else (*s, 1) for s in stops])


class P:
    """A path element. Paints are palette references, "sym" or gradients."""

    def __init__(self, d: str, fill=None, stroke=None, width: float = 0, opacity: float | None = None,
                 evenodd: bool = False):
        self.d, self.fill, self.stroke, self.width = d, fill, stroke, width
        self.opacity, self.evenodd = opacity, evenodd

    def svg(self, paint) -> str:
        out = f'<path d="{self.d}" fill="{paint(self.fill) if self.fill else "none"}"'
        if self.evenodd:
            out += ' fill-rule="evenodd"'
        if self.stroke:
            out += (f' stroke="{paint(self.stroke)}" stroke-width="{n(self.width)}" '
                    'stroke-linecap="round" stroke-linejoin="round"')
        if self.opacity is not None:
            out += f' opacity="{n(self.opacity)}"'
        return out + "/>"


class Raw:
    """Literal SVG (the Boswas OS mark) with its own gradient definitions.
    "{id}" in the text stands for the file's id prefix."""

    def __init__(self, text: str, defs: list[str]):
        self.text, self.defs = text, defs


def F(d: str, paint, opacity: float | None = None, evenodd: bool = False) -> P:
    """Filled shape."""
    return P(d, fill=paint, opacity=opacity, evenodd=evenodd)


def S(d: str, paint, w: float, opacity: float | None = None) -> P:
    """Stroked line with round caps and joins."""
    return P(d, stroke=paint, width=w, opacity=opacity)


def FS(d: str, paint, w: float, opacity: float | None = None, evenodd: bool = False) -> P:
    """Filled shape with a stroke of the same paint (softened corners)."""
    return P(d, fill=paint, stroke=paint, width=w, opacity=opacity, evenodd=evenodd)


# ---------------------------------------------------------------------------
# The light of the coloured icons
# ---------------------------------------------------------------------------
TILT = 0.18  # the light comes from the top, a little from the left


def ramp(name: str, box: tuple, top: str, bottom: str, top_op: float = 1, bottom_op: float = 1) -> Grad:
    """A gradient over a box: `top` at its top (and left), `bottom` at its bottom (and right)."""
    x0, y0, x1, y1 = box
    cx, h = (x0 + x1) / 2, y1 - y0
    return lin(name, cx - TILT * h, y0, cx + TILT * h, y1, (0, top, top_op), (1, bottom, bottom_op))


TIERS = {"light": ("light", "from"), "body": ("from", "to"), "deep": ("to", "deep"),
         "bright": ("light", "to"), "full": ("light", "deep"), "flat": ("from", "from")}


def paint_of(fam: str, tier: str = "body", box: tuple | None = None, d: str | None = None) -> Grad:
    """The gradient of a part in a colour family (`icon.hues` or `icon.materials`):
    body runs from 'from' to 'to', light from 'light' to 'from', deep from 'to' to 'deep'."""
    top, bottom = TIERS[tier]
    spec = family(fam)
    return ramp(f"{fam}-{tier}", box or bbox(d), spec[top], spec[bottom])


def part(d: str, fam: str, tier: str = "body", box: tuple | None = None, opacity: float | None = None) -> P:
    """A filled part of an object, in the gradient of its colour family."""
    return F(d, paint_of(fam, tier, box, d), opacity)


def sheen(d: str, depth: float = 14, box: tuple | None = None, strength: float = 1.0) -> P:
    """Highlight along the top edge of a part: the part again, in white that
    fades out `depth` units below its top."""
    x0, y0, x1, _y1 = box or bbox(d)
    cx = (x0 + x1) / 2
    op = light("highlight-opacity") * strength
    return F(d, lin("sheen", cx, y0, cx, y0 + depth, (0, light("highlight"), op), (1, light("highlight"), 0)))


def shade(d: str, strength: float = 1.0) -> P:
    """The shade a part casts where it lies on another (drawn under it)."""
    return F(d, light("shade"), light("shade-opacity") * strength)


def shadow(cx: float, cy: float, rx: float, ry: float = 12, strength: float = 1.0) -> P:
    """Soft contact shadow under an object: an ellipse fading out to its edge."""
    op = light("shadow-opacity") * strength
    ref = light("shadow")
    return F(ellipse(cx, cy, rx, ry), rad("shadow", cx, cy, rx, ry, (0, ref, op), (0.5, ref, op * 0.55),
                                         (1, ref, 0)))


def edge(d: str, fam: str = "paper", w: float = 3, opacity: float | None = None) -> P:
    """Faint outline that keeps a white part visible on a white background."""
    return S(d, family(fam)["edge"], w, opacity)


def obj(d: str, fam: str, tier: str = "body", depth: float = 14, box=None, strength: float = 1.0) -> list[P]:
    """A lit part: its gradient and the highlight along its top edge."""
    return [part(d, fam, tier, box), sheen(d, depth, box, strength)]


