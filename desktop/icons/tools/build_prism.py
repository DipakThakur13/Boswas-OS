#!/usr/bin/env python3
"""Generate the Boswas Prism icon themes.

Boswas Prism is the icon pack of the native Boswas desktop. Every icon is
drawn here, on a 256x256 grid, and written as a self-contained SVG into

    desktop/icons/Boswas-Prism/scalable/{apps,places,devices,mimetypes,status,actions}/
    desktop/icons/Boswas-Prism-Light/scalable/{status,actions}/

The generated files are committed; re-run this tool after changing a glyph
or desktop/ui/tokens.json:

    python3 desktop/icons/tools/build_prism.py            # regenerate in place
    python3 desktop/icons/tools/build_prism.py --output DIR   # DIR/Boswas-Prism, DIR/Boswas-Prism-Light
    python3 desktop/icons/tools/build_prism.py --table    # README name table

Design rules (see desktop/icons/README.md):
  * every colour comes from desktop/ui/tokens.json (the Prism palette); the
    official Boswas OS mark keeps its own gold and silver, copied from
    desktop/branding/boswas-os-mark.svg by the legacy generator's loader;
  * applications sit on a squircle tile (a superellipse, 232 px) with a
    diagonal gradient in the hue of their category, a soft top highlight and
    no edge; the glyph is line art in the hue's glyph colour with ONE accent
    element. The glyph geometry of the 61 legacy designs is reused from
    build_icons.py, so both packs draw the same shapes;
  * places, devices and mimetypes are objects without a tile (folders,
    hardware, pages);
  * status and action icons are symbolic: one flat colour, bold strokes,
    written twice (cloud.50 for dark panels, ink.900 for light panels);
  * only features Qt's SVG renderer, resvg and librsvg all support: paths,
    linear gradients in user space, solid fills and strokes, opacity and
    fill-rule. No masks, clip paths, filters, CSS, <text>, <image>, <use> or
    nested <svg>. Every id is prefixed with the file's own name.

Python 3 standard library only. Output is deterministic.
"""

