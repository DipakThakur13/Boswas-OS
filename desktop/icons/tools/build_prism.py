def id_prefix(file_name: str) -> str:
    """Id prefix for a file: its name with anything but [A-Za-z0-9-] as '-'."""
    return re.sub(r"[^A-Za-z0-9-]", "-", file_name)


def render(context: str, file_name: str, title: str, glyph, sym: str | None) -> str:
    prefix = id_prefix(file_name)
    defs: list[str] = []
    ids: dict = {}

    def paint(value) -> str:
        if isinstance(value, Grad):
            if value.key not in ids:
                base = f"{prefix}-{value.name}"
                ident, k = base, 2
                while ident in ids.values():
                    ident, k = f"{base}-{k}", k + 1
                ids[value.key] = ident
                defs.append(value.svg(ident))
            return f"url(#{ids[value.key]})"
        return colour(sym if value == "sym" else value)

    body = []
    for el in glyph():
        if isinstance(el, Raw):
            defs.extend(text.replace("{id}", prefix) for text in el.defs)
            body.append(el.text.replace("{id}", prefix))
        else:
            body.append(el.svg(paint))
    text = "\n".join("  " + line_ for el in body for line_ in el.split("\n"))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">\n'
            f"  <title>{title}</title>\n"
            f"  <!-- {HEADER} -->\n"
            + (f"  <defs>\n" + "\n".join(defs) + "\n  </defs>\n" if defs else "") +
            f"{text}\n"
            "</svg>\n")


def all_files():
    """Yield (theme, context, file name, design name, title, drawing, family) for every file."""
    for context, name, title, glyph, aliases, fam in icons():
        for theme in (DARK, LIGHT) if context in SYMBOLIC else (DARK,):
            for file_name in (name,) + tuple(aliases):
                yield theme, context, file_name, name, title, glyph, fam


def build(output: Path) -> list[Path]:
    """Write every icon under output/<theme>/scalable/; remove stale SVGs there."""
    written = []
    for theme, context, file_name, _design, title, glyph, _fam in all_files():
        target = output / theme / "scalable" / context / f"{file_name}.svg"
        target.parent.mkdir(parents=True, exist_ok=True)
        sym = SYMBOLIC_INK[theme] if context in SYMBOLIC else None
        data = render(context, file_name, title, glyph, sym).encode("utf-8")
        if not target.exists() or target.read_bytes() != data:
            target.write_bytes(data)
        written.append(target)
    keep = set(written)
    for theme in (DARK, LIGHT):
        for stale in sorted((output / theme / "scalable").glob("*/*.svg")):
            if stale not in keep:
                stale.unlink()
    return written


def table() -> str:
    """Markdown table of every design, its colour family, its drawing and its theme names."""
    rows = ["| Context | Design | Colour | Drawing | Theme icon names |", "|---|---|---|---|---|"]
    for context, name, title, glyph, aliases, fam in icons():
        names = ", ".join(f"`{x}`" for x in (name,) + tuple(aliases))
        rows.append(f"| {context} | {title} | {fam or 'symbolic'} | {glyph.__doc__.strip()} | {names} |")
    return "\n".join(rows)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Generate the Boswas Prism icon themes.")
    parser.add_argument("--output", type=Path, default=ICONS_DIR,
                        help="directory that holds Boswas-Prism/ and Boswas-Prism-Light/ (default: desktop/icons)")
    parser.add_argument("--table", action="store_true", help="print the README name table")
    args = parser.parse_args(argv)
    if args.table:
        print(table())
        return 0
    files = build(args.output)
    print(f"{len(icons())} designs, {len(files)} files written to {args.output}/{DARK} and {args.output}/{LIGHT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
