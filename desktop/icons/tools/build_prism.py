def describe(text: str) -> str:
    """A legacy glyph description in Prism words (the accent is not gold)."""
    text = re.sub(r"\ba gold\b", "an accent", text.strip())
    text = re.sub(r"\bin gold\b", "in the accent colour", text)
    text = re.sub(r"\bgold\.", "in the accent colour.", text)
    return re.sub(r"\bgold\b", "accent", text)


def from_legacy(glyph):
    """A legacy glyph with its paints renamed: silver -> glyph, gold -> accent,
    navy symbols on a badge -> onaccent. Knock-outs keep the tile paint."""
    def build() -> list[str]:
        return [el.replace("$silver", "$glyph").replace("$gold", "$accent")
                .replace(legacy.NAVY_900, "$onaccent") for el in glyph()]
    build.__doc__ = describe(glyph.__doc__)
    return build


