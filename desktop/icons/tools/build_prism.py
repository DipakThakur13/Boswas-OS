def S(d: str, paint: str = "$glyph", w: float = W, opacity: float | None = None) -> str:
    """Stroked line art with round caps and joins."""
    op = f' opacity="{n(opacity)}"' if opacity is not None else ""
    return (f'<path d="{d}" fill="none" stroke="{paint}" stroke-width="{n(w)}" '
            f'stroke-linecap="round" stroke-linejoin="round"{op}/>')


def F(d: str, paint: str = "$glyph", opacity: float | None = None, evenodd: bool = False) -> str:
    """Filled shape."""
    rule = ' fill-rule="evenodd"' if evenodd else ""
    op = f' opacity="{n(opacity)}"' if opacity is not None else ""
    return f'<path d="{d}" fill="{paint}"{rule}{op}/>'


def FS(d: str, paint: str = "$accent", w: float = 6, opacity: float | None = None,
       evenodd: bool = False) -> str:
    """Filled shape with a thin stroke of the same paint (softened corners)."""
    rule = ' fill-rule="evenodd"' if evenodd else ""
    op = f' opacity="{n(opacity)}"' if opacity is not None else ""
    return (f'<path d="{d}" fill="{paint}"{rule} stroke="{paint}" stroke-width="{n(w)}" '
            f'stroke-linecap="round" stroke-linejoin="round"{op}/>')


def squircle(cx: float, cy: float, a: float, exponent: float = 5.0) -> str:
    """Superellipse |x/a|^e + |y/a|^e = 1 as cubic Beziers (within 0.25 px).

    Nodes are placed by the direction of the outline's normal, so they are
    dense where the corner turns; the handles follow the exact tangents."""
    def node(deg: float) -> tuple[float, float]:
        c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
        if deg % 180 == 90:
            return 0.0, math.copysign(a, s)
        if deg % 180 == 0:
            return math.copysign(a, c), 0.0
        k = (abs(s) / abs(c)) ** (1 / (exponent - 1))
        x = a / (1 + k ** exponent) ** (1 / exponent)
        return math.copysign(x, c), math.copysign(k * x, s)

    quadrant = (0, 6, 14, 24, 35, 45, 55, 66, 76, 84)
    angles = [q * 90 + d for q in range(4) for d in quadrant] + [360]
    x0, y0 = node(0)
    d = [f"M{pt(cx + x0, cy + y0)}"]
    for a0, a1 in zip(angles, angles[1:]):
        (px, py), (qx, qy) = node(a0), node(a1)
        r0, r1 = math.radians(a0), math.radians(a1)
        h = math.hypot(qx - px, qy - py) / (3 * math.cos((r1 - r0) / 4) ** 2)
        d.append(f"C{pt(cx + px - h * math.sin(r0), cy + py + h * math.cos(r0))} "
                 f"{pt(cx + qx + h * math.sin(r1), cy + qy - h * math.cos(r1))} "
                 f"{pt(cx + qx, cy + qy)}")
    return "".join(d) + "Z"


