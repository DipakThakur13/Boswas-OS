ACCENT_TOKEN = "semantic.light.accent"   # the ring's track is white, a light surface


# ---------------------------------------------------------------------------
# Tokens
# ---------------------------------------------------------------------------
_TOKENS: dict = {}


def tokens() -> dict:
    if not _TOKENS:
        _TOKENS.update(json.loads(TOKENS_FILE.read_text(encoding="utf-8")))
    return _TOKENS


def colour(ref: str) -> str:
    """Resolve a token reference to "#RRGGBB".

    "white", "iris.600" name a colour; "semantic.light.accent" names a role
    whose value is such a reference.
    """
    if ref.startswith("semantic."):
        _, theme, role = ref.split(".", 2)
        ref = tokens()["semantic"][theme][role]
    scale, _, shade = ref.partition(".")
    value = tokens()["color"][scale]
    value = value[shade] if shade else value
    if not (isinstance(value, str) and len(value) == 7 and value.startswith("#")):
        raise SystemExit(f"build_cursors: {ref} is not a colour in {TOKENS_FILE}")
    int(value[1:], 16)
    return value.upper()


def mix(a: str, b: str, t: float) -> str:
    """The colour a fraction t of the way from a to b (sRGB values)."""
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(pa, pb))


