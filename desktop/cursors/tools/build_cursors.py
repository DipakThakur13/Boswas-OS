def shape_pencil():
    """A pencil that writes at its lower left end."""
    tip = (5.0, 27.0)
    ax, ay = math.sqrt(0.5), -math.sqrt(0.5)      # along the pencil, away from the tip
    bx, by = math.sqrt(0.5), math.sqrt(0.5)       # across the pencil

    def at(u: float, v: float):
        return tip[0] + u * ax + v * bx, tip[1] + u * ay + v * by

    half, cone, band, end = 2.3, 5.4, 21.0, 25.0
    body = [at(0, 0), at(cone, -half), at(end, -half), at(end, half), at(cone, half)]
    ink = [ink_fill(polygon([at(0, 0), at(2.3, -2.3 * half / cone), at(2.3, 2.3 * half / cone)])),
           ink_line(line(at(cone, -half), at(cone, half))),
           ink_line(line(at(band, -half), at(band, half)))]
    return [Layer([fill(polygon(body, radii=[0.0, 0.0, 1.2, 1.2, 0.0]))], ink)]


