def ring_ink(cx: float, cy: float, r: float, band: float, head: float):
    """The turning arc: it ends at `head` degrees and fades towards its tail.

    The arc is a chain of short pieces from the tail to the head, each a step
    closer to the accent. A piece runs a little under the next one, which is
    drawn over it, so there is no gap between them.
    """
    white, accent = colour(FILL_TOKEN), colour(ACCENT_TOKEN)
    count, longest, shortest, under = 16, 250.0, 30.0, 4.0
    starts = [head - longest + (longest - shortest) * i / (count - 1) for i in range(count)]
    out = []
    for i, start in enumerate(starts):
        last = i == count - 1
        stop = head if last else starts[i + 1] + under
        out.append(f'<path d="{arc(cx, cy, r, start, stop)}" fill="none" '
                   f'stroke="{mix(white, accent, ((i + 1) / count) ** 1.5)}" stroke-width="{n(band)}" '
                   f'stroke-linecap="{"round" if last else "butt"}"/>')
    return out


