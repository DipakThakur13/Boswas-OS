# The arrow. Its white tip is at (3, 3); the outline's tip is the pixel above
# and to the left of it, which is the hotspot.
ARROW_TIP = (3.0, 3.0)
ARROW_HOTSPOT = (2.5, 2.5)
THIN = 15.5                      # centre line of the shapes with a core one unit wide (I-beam, cross)
THIN_HOTSPOT = (15.5, 15.5)
MID = 16.0                       # centre line of the shapes with a core two units wide (double arrows)
MID_HOTSPOT = (16.0, 16.0)


def arrow_points():
    tx, ty = ARROW_TIP
    wing = (10.5, 11.0)          # right end of the head, relative to the tip
    left = 15.4                  # length of the vertical left edge
    notch = 6.3                  # where the tail leaves the lower edge of the head
    lean = math.radians(21.0)    # the tail leans to the right
    tail_length, tail_width = 5.9, 2.5
    dx, dy = math.sin(lean), math.cos(lean)
    c = (notch, wing[1])
    d = (c[0] + tail_length * dx, c[1] + tail_length * dy)
    e = (d[0] - tail_width * dy, d[1] + tail_width * dx)
    # The left edge of the tail meets the 45 degree edge that rises from the lower left corner.
    bx, by = c[0] - tail_width * dy, c[1] + tail_width * dx
    s = (left - bx - by) / (dx + dy)
    f = (bx + s * dx, by + s * dy)
    points = [(0.0, 0.0), wing, c, d, e, f, (0.0, left)]
    return [(tx + x, ty + y) for x, y in points]


def arrow() -> Part:
    return fill(polygon(arrow_points(), radii=[0.0, 0.7, 0.0, 0.7, 0.7, 0.0, 0.7]))


HEAD = 4.0                       # half the width of an arrow head, and its length (45 degree sides)
SHAFT = 1.0                      # half the width of an arrow's shaft
ARROW_REACH = 10.0               # from the centre to the tip of a double arrow


def head_up(tip_y: float):
    """An arrow head that points up: the tip and the two ends of its base."""
    return (MID, tip_y), (MID + HEAD, tip_y + HEAD), (MID - HEAD, tip_y + HEAD)


def double_arrow_points():
    """A vertical double arrow about the centre: heads 8 wide, shaft 2 wide, 20 long."""
    top, bottom = MID - ARROW_REACH, MID + ARROW_REACH
    return [(MID, top), (MID + HEAD, top + HEAD), (MID + SHAFT, top + HEAD),
            (MID + SHAFT, bottom - HEAD), (MID + HEAD, bottom - HEAD), (MID, bottom),
            (MID - HEAD, bottom - HEAD), (MID - SHAFT, bottom - HEAD),
            (MID - SHAFT, top + HEAD), (MID - HEAD, top + HEAD)]


DOUBLE_RADII = [0.0, 0.6, 0.0, 0.0, 0.6, 0.0, 0.6, 0.0, 0.0, 0.6]


def diagonal_arrow_points():
    """A double arrow from the upper left to the lower right; the heads' outer edges follow the axes."""
    a, b = MID - 7.0, MID + 7.0
    leg = HEAD * math.sqrt(2)    # the same head as the upright arrows, turned by 45 degrees
    k = SHAFT / math.sqrt(2)     # half the shaft's width, along each axis
    m0, m1 = a + leg / 2, b - leg / 2
    return [(a, a), (a + leg, a), (m0 + k, m0 - k), (m1 + k, m1 - k), (b, b - leg), (b, b),
            (b - leg, b), (m1 - k, m1 + k), (m0 - k, m0 + k), (a, a + leg)]


