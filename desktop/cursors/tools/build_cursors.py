#!/usr/bin/env python3
"""Generate the sources of the Boswas pointer cursor theme.

Boswas Cursors is the XCursor theme of the native Boswas desktop. Every shape
is drawn here, on a 32x32 grid, and written as a self-contained SVG into

    desktop/cursors/Boswas-Cursors/src/<name>.svg          static shapes
    desktop/cursors/Boswas-Cursors/src/<name>-NN.svg       frames of animated shapes
    desktop/cursors/Boswas-Cursors/cursors.json            hotspots, frames, delays, alternate names
    desktop/cursors/Boswas-Cursors/index.theme

The generated files are committed; re-run this tool after changing a drawing
or desktop/ui/tokens.json:

    python3 desktop/cursors/tools/build_cursors.py             # regenerate in place
    python3 desktop/cursors/tools/build_cursors.py --check     # exit 1 if the committed files differ
    python3 desktop/cursors/tools/build_cursors.py --output DIR   # write DIR/Boswas-Cursors instead
    python3 desktop/cursors/tools/build_cursors.py --table     # README table of shapes and names

install.sh renders the SVGs with rsvg-convert and writes the XCursor files
(tools/xcursor.py); nothing in this file is needed at run time.

Design rules (see desktop/cursors/README.md):
  * one family: a white body with a dark outline of constant width and a
    soft shadow to the lower right. The colours come from
    desktop/ui/tokens.json: white, neutral.950 for the outline and the
    light theme's accent for the turning arc of the busy ring;
  * the grid is 32 units for the nominal size 24, so one unit is one pixel
    at the default size. Edges that run along an axis sit on whole units and
    stay sharp at 24, 48 and 96;
  * a shape is a list of parts. Each part is drawn twice: first in the
    outline colour and widened by the outline on every side, then in white.
    Overlapping parts therefore merge into one silhouette with one outline
    (the fingers and the palm of a hand, the two arrows of "move");
  * the hotspot is given in grid units; install.sh turns it into the pixel
    that contains that point at every size;
  * the SVGs are rendered by librsvg only (at build time), so the shadow may
    use a Gaussian blur filter. Every id is prefixed with the file's name.

Python 3 standard library only. Output is deterministic.
"""

