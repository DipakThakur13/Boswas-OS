# Geometry
# ---------------------------------------------------------------------------
def n(value: float) -> str:
    """A number with at most three decimals and no trailing zeros."""
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def polygon(points, radius: float = 0.0, radii=None) -> str:
    """A closed polygon path; corners are rounded with `radius` (or per vertex with `radii`)."""
    count = len(points)
    out = []
    for i, (x, y) in enumerate(points):
        r = radii[i] if radii is not None else radius
        px, py = points[i - 1]
        qx, qy = points[(i + 1) % count]
        la, lb = math.hypot(px - x, py - y), math.hypot(qx - x, qy - y)
        ux, uy = (px - x) / la, (py - y) / la
        vx, vy = (qx - x) / lb, (qy - y) / lb
        half = math.acos(max(-1.0, min(1.0, ux * vx + uy * vy))) / 2
        if r <= 0 or half < 1e-6 or abs(half - math.pi / 2) < 1e-6:
            out.append(("L", x, y))
            continue
        reach = min(r / math.tan(half), la / 2, lb / 2)
        r = reach * math.tan(half)
        sweep = 1 if ux * vy - uy * vx < 0 else 0
        out.append(("L", x + ux * reach, y + uy * reach))
        out.append(("A", r, sweep, x + vx * reach, y + vy * reach))
    d = []
    for k, seg in enumerate(out):
        if seg[0] == "A":
            d.append(f"A{n(seg[1])} {n(seg[1])} 0 0 {seg[2]} {n(seg[3])} {n(seg[4])}")
        else:
            d.append(f"{'M' if k == 0 else 'L'}{n(seg[1])} {n(seg[2])}")
    return "".join(d) + "Z"


def rect(x0: float, y0: float, x1: float, y1: float, radius: float = 0.0) -> str:
    return polygon([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], radius)


def circle(cx: float, cy: float, r: float) -> str:
    return (f"M{n(cx - r)} {n(cy)}A{n(r)} {n(r)} 0 1 1 {n(cx + r)} {n(cy)}"
            f"A{n(r)} {n(r)} 0 1 1 {n(cx - r)} {n(cy)}Z")


def line(*points) -> str:
    return "".join(f"{'M' if i == 0 else 'L'}{n(x)} {n(y)}" for i, (x, y) in enumerate(points))


def on_circle(cx: float, cy: float, r: float, degrees: float):
    """The point at `degrees` clockwise from twelve o'clock."""
    a = math.radians(degrees)
    return cx + r * math.sin(a), cy - r * math.cos(a)


def arc(cx: float, cy: float, r: float, start: float, end: float) -> str:
    """A clockwise arc from `start` to `end` degrees (clockwise from twelve o'clock)."""
    x0, y0 = on_circle(cx, cy, r, start)
    x1, y1 = on_circle(cx, cy, r, end)
    large = 1 if (end - start) % 360 > 180 else 0
    return f"M{n(x0)} {n(y0)}A{n(r)} {n(r)} 0 {large} 1 {n(x1)} {n(y1)}"


def transpose(points):
    return [(y, x) for x, y in points]


def mirror_x(points, axis: float):
    return [(2 * axis - x, y) for x, y in reversed(points)]


def mirror_y(points, axis: float):
    return [(x, 2 * axis - y) for x, y in reversed(points)]


# ---------------------------------------------------------------------------
# Drawing model
# ---------------------------------------------------------------------------
class Part:
    """One piece of a silhouette: a filled path, or a line of `width` with round ends."""

    def __init__(self, d: str, width: float = 0.0):
        self.d = d
        self.width = width

    def svg(self, grow: float) -> str:
        if self.width:
            return f'<path d="{self.d}" fill="none" stroke-width="{n(self.width + 2 * grow)}"/>'
        if grow:
            return f'<path d="{self.d}" stroke-width="{n(2 * grow)}"/>'
        return f'<path d="{self.d}" stroke="none"/>'


def fill(d: str) -> Part:
    return Part(d)


def stroke(d: str, width: float) -> Part:
    return Part(d, width)


class Layer:
    """Parts that merge into one outlined silhouette, and the ink drawn on top of it."""

    def __init__(self, parts, ink=()):
        self.parts = list(parts)
        self.ink = list(ink)


def ink_line(d: str, width: float = 1.0, cap: str = "butt") -> str:
    return f'<path d="{d}" fill="none" stroke="@OUTLINE@" stroke-width="{n(width)}" stroke-linecap="{cap}"/>'


def ink_fill(d: str) -> str:
    return f'<path d="{d}" fill="@OUTLINE@"/>'


def render(name: str, layers) -> str:
    """The SVG document of one image."""
    white, dark = colour(FILL_TOKEN), colour(OUTLINE_TOKEN)
    shadow_id = f"{name}-shadow"
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f"<!-- {HEADER} -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" '
        f'viewBox="0 0 {CANVAS} {CANVAS}">',
        f"<title>{name}</title>",
        f'<defs><filter id="{shadow_id}" x="0" y="0" width="{CANVAS}" height="{CANVAS}" '
        f'filterUnits="userSpaceOnUse" color-interpolation-filters="sRGB">'
        f'<feGaussianBlur stdDeviation="{n(SHADOW_BLUR)}"/></filter></defs>',
        f'<g filter="url(#{shadow_id})" opacity="{n(SHADOW_OPACITY)}">'
        f'<g transform="translate({n(SHADOW_OFFSET[0])} {n(SHADOW_OFFSET[1])})" fill="#000000" '
        f'stroke="#000000" stroke-linejoin="round" stroke-linecap="round">',
    ]
    for layer in layers:
        out.extend(part.svg(OUTLINE_WIDTH) for part in layer.parts)
    out.append("</g></g>")
    for layer in layers:
        out.append(f'<g fill="{dark}" stroke="{dark}" stroke-linejoin="round" stroke-linecap="round">')
        out.extend(part.svg(OUTLINE_WIDTH) for part in layer.parts)
        out.append("</g>")
        out.append(f'<g fill="{white}" stroke="{white}" stroke-linejoin="round" stroke-linecap="round">')
        out.extend(part.svg(0.0) for part in layer.parts)
        out.append("</g>")
        out.extend(item.replace("@OUTLINE@", dark) for item in layer.ink)
    out.append("</svg>")
    return "\n".join(out) + "\n"


