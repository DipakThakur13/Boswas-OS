#!/usr/bin/env python3
"""Generate the Boswas Prism colour schemes for KDE applications.

KDE applications (Dolphin, Konsole, Okular...) take their colours from a KDE
colour scheme. These two schemes map the Boswas UI tokens (tokens.json) onto
KDE's colour roles, so application windows match the shell and the window
frames of the native Boswas desktop:

    desktop/ui/color-schemes/BoswasPrism.colors        dark (the default)
    desktop/ui/color-schemes/BoswasPrismLight.colors   light

Konsole draws its terminal with a colour scheme of its own, chosen by a
profile; both come from the same tokens:

    desktop/ui/konsole/BoswasPrism.colorscheme         dark
    desktop/ui/konsole/BoswasPrismLight.colorscheme    light
    desktop/ui/konsole/Boswas Prism.profile            the default profile
    desktop/ui/konsole/Boswas Prism Light.profile

The files are committed; re-run this tool after changing tokens.json:

    python3 desktop/ui/tools/build_kde_colors.py           # rewrite
    python3 desktop/ui/tools/build_kde_colors.py --check   # fail if stale

Python 3 standard library only. Output is deterministic.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

UI = Path(__file__).resolve().parent.parent
TOKENS = UI / "tokens.json"
OUTPUT = UI / "color-schemes"
KONSOLE = UI / "konsole"
HEADER = "# Generated by desktop/ui/tools/build_kde_colors.py from tokens.json; do not edit by hand."

SCHEMES = {
    "dark": ("BoswasPrism", "Boswas Prism"),
    "light": ("BoswasPrismLight", "Boswas Prism Light"),
}

# KDE role -> token reference, per scheme. "@name" is a semantic token of the
# scheme; anything else is a palette reference.
FOREGROUND = {
    "dark": {"ForegroundNormal": "@text", "ForegroundInactive": "@text-muted", "ForegroundActive": "iris.300",
             "ForegroundLink": "azure.300", "ForegroundVisited": "orchid.300", "ForegroundNegative": "coral.300",
             "ForegroundNeutral": "sun.400", "ForegroundPositive": "mint.400",
             "DecorationFocus": "iris.400", "DecorationHover": "iris.300"},
    "light": {"ForegroundNormal": "@text", "ForegroundInactive": "@text-muted", "ForegroundActive": "iris.700",
              "ForegroundLink": "azure.700", "ForegroundVisited": "orchid.700", "ForegroundNegative": "coral.700",
              "ForegroundNeutral": "sun.800", "ForegroundPositive": "mint.700",
              "DecorationFocus": "iris.600", "DecorationHover": "iris.500"},
}
# group -> (BackgroundNormal, BackgroundAlternate)
BACKGROUND = {
    "dark": {"Button": ("@surface-raised", "@surface-hover"), "Complementary": ("@background", "@surface"),
             "Header": ("@surface-raised", "@surface"), "Header][Inactive": ("@surface", "@background"),
             "Tooltip": ("@surface-raised", "@surface-hover"), "View": ("@background", "@surface"),
             "Window": ("@surface", "@background")},
    "light": {"Button": ("@surface-raised", "@surface-hover"), "Complementary": ("ink.900", "ink.800"),
              "Header": ("@surface-raised", "@background"), "Header][Inactive": ("@background", "@surface-raised"),
              "Tooltip": ("@surface", "@surface-raised"), "View": ("@surface", "@background"),
              "Window": ("@background", "@surface-raised")},
}
# The selection is the same in both schemes: white text on iris.600 (6:1).
SELECTION = {"BackgroundNormal": "iris.600", "BackgroundAlternate": "iris.700", "ForegroundNormal": "white",
             "ForegroundInactive": "iris.300", "ForegroundActive": "white", "ForegroundLink": "azure.300",
             "ForegroundVisited": "orchid.300", "ForegroundNegative": "coral.300", "ForegroundNeutral": "sun.300",
             "ForegroundPositive": "mint.300", "DecorationFocus": "white", "DecorationHover": "iris.300"}
# The dark Complementary group of the light scheme keeps light text.
COMPLEMENTARY_LIGHT = {"ForegroundNormal": "cloud.50", "ForegroundInactive": "cloud.400", "ForegroundActive": "iris.300",
                       "ForegroundLink": "azure.400", "ForegroundVisited": "orchid.400",
                       "ForegroundNegative": "coral.400", "ForegroundNeutral": "sun.400",
                       "ForegroundPositive": "mint.400", "DecorationFocus": "iris.400", "DecorationHover": "iris.300"}

EFFECTS = """[ColorEffects:Disabled]
Color=56,56,56
ColorAmount=0
ColorEffect=0
ContrastAmount=0.65
ContrastEffect=1
IntensityAmount=0.1
IntensityEffect=2

[ColorEffects:Inactive]
ChangeSelectionColor=true
Color=112,111,110
ColorAmount=0.025
ColorEffect=2
ContrastAmount=0.1
ContrastEffect=2
Enable=false
IntensityAmount=0
IntensityEffect=0
"""


def load_tokens() -> dict:
    with TOKENS.open(encoding="utf-8") as handle:
        return json.load(handle)


def resolve(tokens: dict, scheme: str, reference: str) -> str:
    """A token reference as '#RRGGBB'."""
    if reference.startswith("@"):
        reference = tokens["semantic"][scheme][reference[1:]]
    family, _, shade = reference.partition(".")
    value = tokens["color"][family]
    return value[shade] if shade else value


def rgb(hex_colour: str) -> str:
    """'#RRGGBB' as KDE writes colours: 'R,G,B'."""
    return ",".join(str(int(hex_colour[i:i + 2], 16)) for i in (1, 3, 5))


def groups(tokens: dict, scheme: str) -> dict[str, dict[str, str]]:
    """Every [Colors:*] and [WM] group of a scheme as {group: {key: '#RRGGBB'}}."""
    def colours(mapping: dict[str, str]) -> dict[str, str]:
        return {key: resolve(tokens, scheme, reference) for key, reference in mapping.items()}

    out: dict[str, dict[str, str]] = {}
    for group, (normal, alternate) in BACKGROUND[scheme].items():
        foreground = COMPLEMENTARY_LIGHT if (scheme, group) == ("light", "Complementary") else FOREGROUND[scheme]
        out[f"Colors:{group}"] = colours({"BackgroundNormal": normal, "BackgroundAlternate": alternate, **foreground})
    out["Colors:Selection"] = colours(SELECTION)
    out["WM"] = colours({
        "activeBackground": "@surface-raised", "activeBlend": "@text", "activeForeground": "@text",
        "inactiveBackground": "@surface" if scheme == "dark" else "@background",
        "inactiveBlend": "@text-muted", "inactiveForeground": "@text-muted",
    })
    return out


def render(tokens: dict, scheme: str) -> str:
    file_id, name = SCHEMES[scheme]
    parts = [HEADER, "", EFFECTS]
    data = groups(tokens, scheme)
    for group in sorted(g for g in data if g.startswith("Colors:")):
        parts.append(f"[{group}]")
        parts.extend(f"{key}={rgb(value)}" for key, value in sorted(data[group].items()))
        parts.append("")
    parts += ["[General]", f"ColorScheme={file_id}", f"Name={name}", "shadeSortColumn=true", "",
              "[KDE]", "contrast=4", "", "[WM]"]
    parts.extend(f"{key}={rgb(value)}" for key, value in sorted(data["WM"].items()))
    return "\n".join(parts) + "\n"


# The sixteen terminal colours (black, red, green, yellow, blue, magenta,
# cyan, white): (normal, intense) per scheme. On the dark background the 400
# shades carry the text and the 300 shades are the intense ones. On the
# light background only the darkest shades reach 4.5:1, so the intense
# colours repeat them (bold text still stands out by its weight).
TERMINAL = {
    "dark": [("ink.600", "ink.500"), ("coral.400", "coral.300"), ("mint.400", "mint.300"), ("sun.400", "sun.300"),
             ("azure.400", "azure.300"), ("orchid.400", "orchid.300"), ("sky.400", "sky.300"),
             ("cloud.200", "white")],
    "light": [("ink.900", "ink.600"), ("coral.700", "coral.700"), ("mint.700", "mint.700"), ("sun.800", "sun.800"),
              ("azure.700", "azure.700"), ("orchid.700", "orchid.700"), ("sky.700", "sky.700"),
              ("cloud.600", "ink.500")],
}
# The same shell start and font as the preset profiles (desktop/presets).
TERMINAL_COMMAND = "/usr/bin/bash --rcfile /usr/share/boswas/terminal/bashrc"
TERMINAL_FONT = "Hack,11"


def mix(first: str, second: str, amount: float) -> str:
    """`first` moved `amount` (0..1) of the way to `second`, as '#RRGGBB'."""
    a = [int(first[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(second[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * amount):02X}" for x, y in zip(a, b))


def terminal_colours(tokens: dict, scheme: str) -> dict[str, str]:
    """Every colour of a Konsole scheme as {section: '#RRGGBB'}."""
    background = resolve(tokens, scheme, "@background")
    foreground = resolve(tokens, scheme, "@text")
    toward = "#FFFFFF" if scheme == "dark" else "#000000"
    out = {"Background": background, "BackgroundFaint": background,
           "BackgroundIntense": mix(background, toward, 0.06)}
    for index, (normal, intense) in enumerate(TERMINAL[scheme]):
        colour = resolve(tokens, scheme, normal)
        out[f"Color{index}"] = colour
        out[f"Color{index}Faint"] = mix(colour, background, 0.4)
        out[f"Color{index}Intense"] = resolve(tokens, scheme, intense)
    out["Foreground"] = foreground
    out["ForegroundFaint"] = mix(foreground, background, 0.35)
    out["ForegroundIntense"] = mix(foreground, toward, 0.6)
    return out


def render_konsole_scheme(tokens: dict, scheme: str) -> str:
    _file_id, name = SCHEMES[scheme]
    parts = [f"# {name} Konsole colour scheme.", HEADER, ""]
    for section, colour in terminal_colours(tokens, scheme).items():
        parts += [f"[{section}]", f"Color={rgb(colour)}", ""]
    parts += ["[General]", "Blur=false", "ColorRandomization=false", f"Description={name}", "Opacity=1", "Wallpaper="]
    return "\n".join(parts) + "\n"


def render_konsole_profile(scheme: str) -> str:
    file_id, name = SCHEMES[scheme]
    return "\n".join([
        f"# {name} Konsole profile.", HEADER, "",
        "[Appearance]", f"ColorScheme={file_id}", f"Font={TERMINAL_FONT}", "",
        "[General]", f"Command={TERMINAL_COMMAND}", f"Name={name}", "Parent=FALLBACK/", "",
        "[Scrolling]", "HistorySize=10000", "",
        "[Terminal Features]", "BlinkingCursorEnabled=false",
    ]) + "\n"


def outputs(tokens: dict) -> dict[Path, str]:
    """Every generated file and its content."""
    files: dict[Path, str] = {}
    for scheme, (file_id, name) in SCHEMES.items():
        files[OUTPUT / f"{file_id}.colors"] = render(tokens, scheme)
        files[KONSOLE / f"{file_id}.colorscheme"] = render_konsole_scheme(tokens, scheme)
        files[KONSOLE / f"{name}.profile"] = render_konsole_profile(scheme)
    return files


def main(argv: list[str]) -> int:
    check = argv == ["--check"]
    if argv and not check:
        print(__doc__, file=sys.stderr)
        return 2
    tokens = load_tokens()
    stale = []
    for path, text in outputs(tokens).items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(UI.parent.parent)}")
    if stale:
        print("stale colour schemes (run desktop/ui/tools/build_kde_colors.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
