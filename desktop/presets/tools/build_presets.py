def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def outputs(data: dict) -> dict[str, str]:
    files: dict[str, str] = {}
    for p in data["presets"]:
        files[f"color-schemes/{scheme_name(p)}.colors"] = colors_file(p)
        files[f"konsole/{scheme_name(p)}.colorscheme"] = konsole_scheme(p)
        files[f"konsole/{profile_name(p)}"] = konsole_profile(p)
        lnf = f"look-and-feel/{lnf_id(p)}"
        files[f"{lnf}/metadata.json"] = lnf_metadata(p)
        files[f"{lnf}/contents/defaults"] = lnf_defaults(p)
        files[f"{lnf}/contents/layouts/org.kde.plasma.desktop-layout.js"] = layout_js(p)
        wall = f"wallpapers/{wallpaper_name(p)}"
        files[f"{wall}/metadata.json"] = wallpaper_metadata(wallpaper_name(p), p["name"])
        files[f"{wall}/light.svg"] = wallpaper_svg(p, "light")
        files[f"{wall}/dark.svg"] = wallpaper_svg(p, "dark")
        files[f"{wall}/lock.svg"] = wallpaper_svg(p, primary(p), lock=True)
        files[f"previews/{p['id']}.svg"] = preview_svg(p)
    # The system default wallpaper name ("Boswas"): a copy of the default preset's.
    files["wallpapers/Boswas/metadata.json"] = wallpaper_metadata("Boswas", "Boswas")
    return files


def write_tree(root: Path, files: dict[str, str], prune: bool) -> list[str]:
    changed = []
    for rel, text in sorted(files.items()):
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        old = path.read_bytes() if path.exists() else None
        new = text.encode("utf-8")
        if old != new:
            with path.open("w", encoding="utf-8", newline="") as handle:
                handle.write(text)
            changed.append(rel)
    if prune:
        for top in GENERATED_DIRS:
            base = root / top
            if not base.exists():
                continue
            for path in sorted(base.rglob("*"), reverse=True):
                rel = path.relative_to(root).as_posix()
                if path.is_file() and rel not in files:
                    path.unlink()
                    changed.append(f"{rel} (removed)")
                elif path.is_dir() and not any(path.iterdir()):
                    path.rmdir()
    return changed


def stale(root: Path, files: dict[str, str]) -> list[str]:
    problems = []
    for rel, text in sorted(files.items()):
        path = root / rel
        if not path.exists():
            problems.append(f"missing: {rel}")
        elif path.read_bytes() != text.encode("utf-8"):
            problems.append(f"out of date: {rel}")
    for top in GENERATED_DIRS:
        base = root / top
        if base.exists():
            for path in sorted(base.rglob("*")):
                rel = path.relative_to(root).as_posix()
                if path.is_file() and rel not in files:
                    problems.append(f"not generated: {rel}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--presets", type=Path, default=PRESETS_DIR / "presets.json",
                        help="presets file (default: %(default)s)")
    parser.add_argument("--output", type=Path, help="write the generated tree here")
    parser.add_argument("--check", action="store_true", help="only check that files are up to date")
    args = parser.parse_args(argv)

    files = outputs(load(args.presets))
    if args.check:
        problems = stale(args.output or PRESETS_DIR, files)
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            print("Run desktop/presets/tools/build_presets.py to regenerate.", file=sys.stderr)
        return 1 if problems else 0
    root = args.output or PRESETS_DIR
    changed = write_tree(root, files, prune=True)
    for rel in changed:
        print(rel)
    print(f"{len(files)} files, {len(changed)} changed", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
