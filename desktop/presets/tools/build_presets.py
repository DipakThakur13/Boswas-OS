# A motif draws in two layers: "back" (behind the orbit) and "front" (in front
# of it, e.g. a horizon that hides the lower rings). Each one also places the
# blade, the third element of the mark's geometry.

def motif_horizon(svg: Svg, v: dict, ctx: dict, layer: str) -> None:
    """A planet horizon lit in the accent colour along its rim."""
    fx, fy = ctx["focus"]
    if layer == "back":
        if not ctx["lock"]:
            _blade(svg, stem_box(fx, fy, ctx["radii"][2]), v["accent_hi"], 0.06, 0.0, edge=0.20, soft=22)
        return
    top_c, bottom_c = v["motif_colors"]
    pcx, pr = 1450.0, 3600.0
    top = 1780.0 if ctx["lock"] else 1700.0
    pcy = top + pr
    # Atmosphere above the rim.
    air = svg.radial([(0, v["accent_hi"], 0.22), (0.45, v["accent"], 0.07), (1, v["accent"], 0)],
                     pcx + 250, top, 2300, 1.0, 0.36)
    svg.add(f'<rect width="{W}" height="{H}" fill="{air}"/>')
    # The planet.
    body = svg.linear([(0, top_c), (1, bottom_c)], 0, top, 0, H)
    svg.add(f'<circle cx="{num(pcx)}" cy="{num(pcy)}" r="{num(pr)}" fill="{body}"/>')
    # Rim light, brightest just right of the peak, fading towards both sides.
    rim = svg.linear([(0, v["accent"], 0), (0.32, v["accent"], 0.55), (0.46, v["accent_hi"], 0.95),
                      (0.68, v["accent"], 0.4), (1, v["accent"], 0)], -200, 0, 3500, 0)
    svg.add(f'<circle cx="{num(pcx)}" cy="{num(pcy)}" r="{num(pr)}" fill="none" stroke="{rim}" '
            f'stroke-width="40" stroke-opacity="0.35" filter="{svg.blur(26)}"/>')
    svg.add(f'<circle cx="{num(pcx)}" cy="{num(pcy)}" r="{num(pr)}" fill="none" stroke="{rim}" stroke-width="4"/>')


