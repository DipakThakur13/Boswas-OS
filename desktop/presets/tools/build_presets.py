def color_groups(p: dict) -> dict[str, dict[str, str]]:
    c = p["palette"]

    def group(bg: str, alt: str, text: str | None = None, muted: str | None = None,
              strict: bool = False) -> dict[str, str]:
        text = text or c["text"]
        muted = muted or c["muted"]
        values = {
            "BackgroundAlternate": alt,
            "BackgroundNormal": bg,
            "DecorationFocus": c["accent"],
            "DecorationHover": c["accent_hover"],
            "ForegroundActive": c["accent_text"],
            "ForegroundInactive": muted,
            "ForegroundLink": c["link"],
            "ForegroundNegative": c["negative"],
            "ForegroundNeutral": c["neutral"],
            "ForegroundNormal": text,
            "ForegroundPositive": c["positive"],
            "ForegroundVisited": c["visited"],
        }
        if strict:
            # A background of the opposite lightness (Complementary on a light
            # scheme): keep every foreground readable on it.
            for key in ("ForegroundActive", "ForegroundLink", "ForegroundNegative",
                        "ForegroundNeutral", "ForegroundPositive", "ForegroundVisited"):
                values[key] = readable(values[key], bg)
            for key in ("DecorationFocus", "DecorationHover"):
                values[key] = readable(values[key], bg, 3.0)
        return values

    selection = group(c["selection"], c["selection_alt"], c["selection_text"],
                      mix(c["selection_text"], c["selection"], 0.3), strict=True)
    selection["DecorationFocus"] = c["accent"]
    selection["DecorationHover"] = c["accent_hover"]
    selection["ForegroundActive"] = c["selection_text"]

    return {
        "Colors:Button": group(c["button"], c["button_alt"]),
        "Colors:Complementary": group(c["complementary"], c["complementary_alt"],
                                      c["complementary_text"], c["complementary_muted"],
                                      strict=is_dark(c["complementary"]) != is_dark(c["window"])),
        "Colors:Header": group(c["header"], c["header_alt"]),
        "Colors:Header][Inactive": group(c["header_inactive"], c["header_alt"]),
        "Colors:Selection": selection,
        "Colors:Tooltip": group(c["tooltip"], c["window_alt"]),
        "Colors:View": group(c["view"], c["view_alt"]),
        "Colors:Window": group(c["window"], c["window_alt"]),
    }


def colors_file(p: dict) -> str:
    c = p["palette"]
    sections: list[tuple[str, list[tuple[str, str]]]] = [
        ("ColorEffects:Disabled", [
            ("Color", "56,56,56"), ("ColorAmount", "0"), ("ColorEffect", "0"),
            ("ContrastAmount", "0.65"), ("ContrastEffect", "1"),
            ("IntensityAmount", "0.1"), ("IntensityEffect", "2"),
        ]),
        ("ColorEffects:Inactive", [
            ("ChangeSelectionColor", "true"), ("Color", "112,111,110"), ("ColorAmount", "0.025"),
            ("ColorEffect", "2"), ("ContrastAmount", "0.1"), ("ContrastEffect", "2"),
            ("Enable", "false"), ("IntensityAmount", "0"), ("IntensityEffect", "0"),
        ]),
    ]
    for name, values in color_groups(p).items():
        sections.append((name, [(key, triplet(values[key])) for key in COLOR_KEYS]))
    sections.append(("General", [
        ("ColorScheme", scheme_name(p)),
        ("Name", p["name"]),
        ("shadeSortColumn", "true"),
    ]))
    sections.append(("KDE", [("contrast", "4")]))
    dark = p["variant"] == "dark"
    sections.append(("WM", [
        ("activeBackground", triplet(c["header"])),
        ("activeBlend", triplet(c["text"] if dark else c["header"])),
        ("activeForeground", triplet(c["text"])),
        ("inactiveBackground", triplet(c["header_inactive"])),
        ("inactiveBlend", triplet(c["muted"] if dark else c["header_inactive"])),
        ("inactiveForeground", triplet(c["muted"])),
    ]))
    return ini(sections, f"{p['name']} colour scheme ({p['variant']}).\n{NOTICE}")


