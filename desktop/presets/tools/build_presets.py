def rgb(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def hexcolor(channels) -> str:
    return "#%02X%02X%02X" % tuple(max(0, min(255, int(round(c)))) for c in channels)


def triplet(value: str) -> str:
    return "%d,%d,%d" % rgb(value)


def mix(a: str, b: str, t: float) -> str:
    """Blend a towards b (t = 0 gives a, t = 1 gives b)."""
    return hexcolor(x + (y - x) * t for x, y in zip(rgb(a), rgb(b)))


def luminance(value: str) -> float:
    def linear(channel: int) -> float:
        c = channel / 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (linear(c) for c in rgb(value))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: str, b: str) -> float:
    high, low = sorted((luminance(a), luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def is_dark(value: str) -> bool:
    return contrast(value, "#FFFFFF") > contrast(value, "#000000")


def readable(color: str, background: str, ratio: float = 4.5) -> str:
    """Move color towards white (dark background) or black (light background)
    until it reaches the contrast ratio against background."""
    target = "#FFFFFF" if is_dark(background) else "#000000"
    out, step = color, 0
    while contrast(out, background) < ratio and step < 20:
        step += 1
        out = mix(color, target, step / 20.0)
    return out


# --------------------------------------------------------------------------
# Small formatting helpers
# --------------------------------------------------------------------------

def num(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def ini(sections: list[tuple[str, list[tuple[str, str]]]], comment: str = "") -> str:
    lines = [f"# {line}" if line else "#" for line in comment.splitlines()] if comment else []
    if lines:
        lines.append("")
    for name, entries in sections:
        lines.append(f"[{name}]")
        lines.extend(f"{key}={value}" for key, value in entries)
        lines.append("")
    return "\n".join(lines)


def dump_json(data) -> str:
    return json.dumps(data, indent=4, ensure_ascii=True) + "\n"


