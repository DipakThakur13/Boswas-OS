def wallpaper_svg(p: dict, variant: str, lock: bool = False) -> str:
    wp = p["wallpaper"]
    v = wp[variant]
    motif = MOTIFS[wp["motif"]]
    plain = wp["motif"] == "classic"
    fx, fy = wp["focus"]
    mark_h = wp["mark_height"]
    if lock:
        # Keep the centre and left calm for the clock and the password field.
        fx, fy = max(fx, 3000.0), fy + 120
        mark_h *= 0.8
    kind = "lock screen" if lock else f"{variant} wallpaper"
    svg = Svg("w", W, H, f"{p['name']} {kind}")
    r0 = mark_h * MARK_RING / MARK_H
    light = not is_dark(v["base"][1])
    ctx = {"focus": (fx, fy), "lock": lock, "id": p["id"], "light": light,
           "radii": [r0 * 1.55 * 1.42 ** i for i in range(5)]}
    radii = ctx["radii"]

    _base(svg, v, vertical=plain)
    _glows(svg, v, fx, fy)
    motif(svg, v, ctx, "back")
    _orbit(svg, v, fx, fy, r0, count=3 if (lock or plain) else 5)
    motif(svg, v, ctx, "front")
    if lock:
        _trail(svg, v, fx, fy, radii[1], 215, 285, width=5, dot=12, strength=0.75, light=light)
    else:
        _trail(svg, v, fx, fy, radii[1], 200, 292, strength=0.7 if plain else 1.0, light=light)
        if not plain:
            _trail(svg, v, fx, fy, radii[3], 18, 46, width=3, dot=0, strength=0.5)
    _mark(svg, fx, fy, mark_h, v["mark"], v["mark_opacity"])
    return svg.render()


