def konsole_scheme(p: dict) -> str:
    t = p["terminal"]
    bg, fg, colors = t["background"], t["foreground"], t["colors"]
    toward = "#FFFFFF" if is_dark(bg) else "#000000"
    sections = [
        ("Background", [("Color", triplet(bg))]),
        ("BackgroundFaint", [("Color", triplet(bg))]),
        ("BackgroundIntense", [("Color", triplet(mix(bg, toward, 0.06)))]),
    ]
    for i in range(8):
        normal, intense = colors[i], colors[i + 8]
        sections.append((f"Color{i}", [("Color", triplet(normal))]))
        sections.append((f"Color{i}Faint", [("Color", triplet(mix(normal, bg, 0.4)))]))
        sections.append((f"Color{i}Intense", [("Color", triplet(intense))]))
    sections += [
        ("Foreground", [("Color", triplet(fg))]),
        ("ForegroundFaint", [("Color", triplet(mix(fg, bg, 0.35)))]),
        ("ForegroundIntense", [("Color", triplet(mix(fg, toward, 0.6)))]),
        ("General", [
            ("Blur", "false"),
            ("ColorRandomization", "false"),
            ("Description", p["name"]),
            ("Opacity", "1"),
            ("Wallpaper", ""),
        ]),
    ]
    return ini(sections, f"{p['name']} Konsole colour scheme.\n{NOTICE}")


