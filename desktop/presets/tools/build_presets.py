class Svg:
    """A tiny SVG writer. Every id is prefixed so that documents can be nested
    (previews include the wallpaper) without clashes."""

    def __init__(self, prefix: str, width: int, height: int, title: str):
        self.prefix = prefix
        self.width, self.height = width, height
        self.title = title
        self.defs: list[str] = []
        self.body: list[str] = []
        self.count = 0

    def new_id(self, name: str) -> str:
        self.count += 1
        return f"{self.prefix}-{name}{self.count}"

    def add(self, element: str) -> None:
        self.body.append(element)

    def define(self, element: str) -> None:
        self.defs.append(element)

    def render(self) -> str:
        out = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.width}" height="{self.height}" '
            f'viewBox="0 0 {self.width} {self.height}">',
            f"  <title>{self.title}</title>",
            f"  <!-- {NOTICE} -->",
        ]
        if self.defs:
            out.append("  <defs>")
            out.extend(f"    {d}" for d in self.defs)
            out.append("  </defs>")
        out.extend(f"  {b}" for b in self.body)
        out.append("</svg>")
        return "\n".join(out) + "\n"

    # Paint servers and filters ------------------------------------------

    def linear(self, stops, x1, y1, x2, y2) -> str:
        gid = self.new_id("lin")
        self.define(
            f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{num(x1)}" y1="{num(y1)}" '
            f'x2="{num(x2)}" y2="{num(y2)}">{_stops(stops)}</linearGradient>')
        return f"url(#{gid})"

    def radial(self, stops, cx, cy, r, sx: float = 1.0, sy: float = 1.0) -> str:
        """Radial gradient; sx/sy stretch it into an ellipse around (cx, cy)."""
        gid = self.new_id("rad")
        transform = ""
        if sx != 1.0 or sy != 1.0:
            transform = (f' gradientTransform="translate({num(cx)} {num(cy)}) scale({num(sx)} {num(sy)}) '
                         f'translate({num(-cx)} {num(-cy)})"')
        self.define(
            f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{num(cx)}" cy="{num(cy)}" '
            f'r="{num(r)}"{transform}>{_stops(stops)}</radialGradient>')
        return f"url(#{gid})"

    def blur(self, deviation: float) -> str:
        fid = self.new_id("blur")
        m = deviation * 4
        self.define(
            f'<filter id="{fid}" filterUnits="userSpaceOnUse" x="{num(-m)}" y="{num(-m)}" '
            f'width="{num(self.width + 2 * m)}" height="{num(self.height + 2 * m)}">'
            f'<feGaussianBlur stdDeviation="{num(deviation)}"/></filter>')
        return f"url(#{fid})"


def _stops(stops) -> str:
    out = []
    for stop in stops:
        offset, color = stop[0], stop[1]
        opacity = stop[2] if len(stop) > 2 else 1.0
        extra = "" if opacity >= 1.0 else f' stop-opacity="{num(opacity)}"'
        out.append(f'<stop offset="{num(offset)}" stop-color="{color}"{extra}/>')
    return "".join(out)


def polar(cx: float, cy: float, r: float, angle: float) -> tuple[float, float]:
    a = math.radians(angle)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def arc_path(cx: float, cy: float, r: float, start: float, end: float) -> str:
    """Clockwise arc (screen coordinates, angles in degrees, 0 = east)."""
    x0, y0 = polar(cx, cy, r, start)
    x1, y1 = polar(cx, cy, r, end)
    large = 1 if (end - start) % 360 > 180 else 0
    return f"M{num(x0)} {num(y0)}A{num(r)} {num(r)} 0 {large} 1 {num(x1)} {num(y1)}"


def blade_path(x: float, y: float, w: float, h: float) -> str:
    """The stem of the mark: square top-left and bottom-right corners, the
    other two rounded into quarter ellipses."""
    top, bottom = 0.28 * h, 0.32 * h
    return (f"M{num(x)} {num(y)}A{num(w)} {num(top)} 0 0 1 {num(x + w)} {num(y + top)}"
            f"L{num(x + w)} {num(y + h)}A{num(w)} {num(bottom)} 0 0 1 {num(x)} {num(y + h - bottom)}Z")


def stem_box(cx: float, cy: float, ring_radius: float) -> tuple[float, float, float, float]:
    """Where the stem sits when the mark's ring has radius ring_radius around (cx, cy)."""
    s = ring_radius / MARK_RING
    x, y, w, h = MARK_STEM
    return cx + (x - MARK_CX) * s, cy + (y - MARK_CY) * s, w * s, h * s


class Rng:
    """Deterministic pseudo-random numbers (LCG), so sources are reproducible."""

    def __init__(self, seed: str):
        self.state = sum((i + 1) * ord(ch) for i, ch in enumerate(seed)) or 1

    def next(self) -> float:
        self.state = (1103515245 * self.state + 12345) % 2147483648
        return self.state / 2147483648.0

    def uniform(self, a: float, b: float) -> float:
        return a + (b - a) * self.next()


# --------------------------------------------------------------------------
# Wallpapers
# --------------------------------------------------------------------------
#
# Every wallpaper is built from the geometry of the Boswas OS mark:
#   * the orbit: rings concentric with the mark's ring, drawn around a focus,
#   * the trail: an arc on one ring that ends in the dot (a satellite),
#   * the blade: the stem of the mark, as a soft beam or glass plane,
#   * the mark itself at the focus, faint (it never dominates).
# The motif (horizon, aurora, waves...) changes the mood; the accent colour,
# the darkness and the motif are the only things that differ between presets.

BRANDING = "../../../branding"


def _mark(svg: Svg, cx: float, cy: float, height: float, fill: str, opacity: float,
          branding: str = BRANDING) -> None:
    width = height * MARK_W / MARK_H
    x = cx - MARK_CX / MARK_W * width
    y = cy - MARK_CY / MARK_H * height
    if fill == "colour":
        ref = f'href="{branding}/boswas-os-mark.svg"'
    else:
        ref = f'href="{branding}/boswas-os-mark-mono.svg" data-fill="{fill}"'
    svg.add(f'<image x="{num(x)}" y="{num(y)}" width="{num(width)}" height="{num(height)}" '
            f'{ref} opacity="{num(opacity)}"/>')


def _base(svg: Svg, v: dict, vertical: bool = False) -> None:
    c0, c1, c2 = v["base"]
    if vertical:
        fill = svg.linear([(0, c0), (0.55, c1), (1, c2)], 0, 0, 0, H)
    else:
        fill = svg.linear([(0, c0), (0.55, c1), (1, c2)], 0, 0, W, H)
    svg.add(f'<rect width="{W}" height="{H}" fill="{fill}"/>')


def _glows(svg: Svg, v: dict, fx: float, fy: float, scale: float = 1.0) -> None:
    if v["glow_opacity"] > 0:
        fill = svg.radial([(0, v["glow"], v["glow_opacity"]),
                           (0.5, v["glow"], v["glow_opacity"] * 0.3),
                           (1, v["glow"], 0)], fx, fy, 1500 * scale)
        svg.add(f'<rect width="{W}" height="{H}" fill="{fill}"/>')
    if v["ambient_opacity"] > 0:
        fill = svg.radial([(0, v["ambient"], v["ambient_opacity"]), (1, v["ambient"], 0)],
                          420, H + 60, 1700)
        svg.add(f'<rect width="{W}" height="{H}" fill="{fill}"/>')


def _orbit(svg: Svg, v: dict, fx: float, fy: float, r0: float, count: int = 5,
           ratio: float = 1.42, first: float = 1.55, width: float = 3.0) -> list[float]:
    radii = [r0 * first * ratio ** i for i in range(count)]
    parts = []
    for i, r in enumerate(radii):
        opacity = v["ring_opacity"] * max(0.25, 1.0 - 0.18 * i)
        parts.append(f'<circle cx="{num(fx)}" cy="{num(fy)}" r="{num(r)}" '
                     f'stroke-opacity="{num(opacity)}" stroke-width="{num(width)}"/>')
    svg.add(f'<g fill="none" stroke="{v["ring"]}">' + "".join(parts) + "</g>")
    return radii


def _trail(svg: Svg, v: dict, fx: float, fy: float, r: float, start: float, end: float,
           width: float = 6.0, dot: float = 17.0, strength: float = 1.0, light: bool = False) -> None:
    """An arc on a ring of the orbit. With a dot, it is a comet trail ending in
    the dot of the mark; without, a short highlight fading out at both ends."""
    x0, y0 = polar(fx, fy, r, start)
    x1, y1 = polar(fx, fy, r, end)
    if dot > 0:
        stops = [(0, v["accent"], 0), (0.7, v["accent"], 0.55 * strength), (1, v["accent_hi"], 0.95 * strength)]
    else:
        stops = [(0, v["accent"], 0), (0.5, v["accent_hi"], 0.8 * strength), (1, v["accent"], 0)]
    stroke = svg.linear(stops, x0, y0, x1, y1)
    svg.add(f'<path d="{arc_path(fx, fy, r, start, end)}" fill="none" stroke="{stroke}" '
            f'stroke-width="{num(width)}" stroke-linecap="round"/>')
    if dot > 0:
        # A glow around the dot on dark artwork; on light artwork a dark glow
        # would read as a smudge, so the halo is white there.
        halo_color = "#FFFFFF" if light else v["accent_hi"]
        halo = svg.radial([(0, halo_color, (0.7 if light else 0.45) * strength), (1, halo_color, 0)],
                          x1, y1, dot * 7)
        svg.add(f'<circle cx="{num(x1)}" cy="{num(y1)}" r="{num(dot * 7)}" fill="{halo}"/>')
        svg.add(f'<circle cx="{num(x1)}" cy="{num(y1)}" r="{num(dot)}" fill="{v["accent_hi"]}" '
                f'fill-opacity="{num(min(1.0, strength))}"/>')


def _blade(svg: Svg, box, color: str, top: float, bottom: float, edge: float = 0.0,
           soft: float = 0.0, dashed: bool = False, edge_color: str | None = None) -> None:
    """The stem of the mark at large scale: a soft glass plane or light shaft
    (fill), with an optional fine edge that fades out downwards."""
    x, y, w, h = box
    y = max(y, 70.0)   # keep the blade's square top corner in view
    d = blade_path(x, y, w, h)
    if top > 0 or bottom > 0:
        fill = svg.linear([(0, color, top), (1, color, bottom)], x, y, x + w * 0.3, y + h)
        filt = f' filter="{svg.blur(soft)}"' if soft else ""
        svg.add(f'<path d="{d}" fill="{fill}"{filt}/>')
    if edge > 0:
        ec = edge_color or color
        stroke = svg.linear([(0, ec, edge), (0.55, ec, edge * 0.35), (1, ec, 0)], x, y, x, y + h)
        dash = ' stroke-dasharray="14 12"' if dashed else ""
        svg.add(f'<path d="{d}" fill="none" stroke="{stroke}" stroke-width="3"{dash}/>')


def _ribbon(svg: Svg, d: str, width: float, opacity: float, colors, soft) -> None:
    a, b, c = colors
    stroke = svg.linear([(0, a, 0), (0.25, a, 1), (0.6, b, 1), (1, c, 0.2)], 0, 0, W, 0)
    svg.add(f'<path d="{d}" fill="none" stroke="{stroke}" stroke-width="{num(width)}" '
            f'stroke-opacity="{num(opacity)}" stroke-linecap="round" filter="{soft}"/>')


def _cloud(svg: Svg, cx: float, cy: float, rx: float, ry: float, color: str, opacity: float) -> None:
    """A soft elliptical cloud (radial gradient, no filter: smooth and cheap)."""
    fill = svg.radial([(0, color, opacity), (0.35, color, opacity * 0.62), (0.7, color, opacity * 0.2),
                       (1, color, 0)], cx, cy, rx, 1.0, ry / rx)
    svg.add(f'<rect width="{W}" height="{H}" fill="{fill}"/>')


