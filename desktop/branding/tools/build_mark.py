#!/usr/bin/env python3
"""Draw the Boswas OS mark and write its files.

The mark is a lowercase "b" built from three shapes, drawn here from first
principles (no tracing, no artwork in between):

  * the stem: a tall pane with fully rounded ends, in front;
  * the bowl: a round band behind the stem, cut clear of it by a gap, so
    the stem stands in front of it and casts a soft shadow on it;
  * the dot: a warm point of light in the counter, the dot of the first
    Boswas OS logo.

Light comes from the top left: the stem and the bowl run from light to
deep blue, the bowl darkens towards the stem's shadow, and both carry a
soft white sheen at the top. Every colour is a palette colour of
desktop/ui/tokens.json (azure, sky, iris and sun, and white).

Geometry, in the 256 x 256 view box (y down), see GEOMETRY:

  stem   x 42..84, y 10..246, ends rounded by half its width (21)
  bowl   centre (128, 160), outer radius 86, band 40 (inner radius 46),
         cut at x = 94, ten units clear of the stem
  dot    centre (134, 160), radius 18: centred in the open counter
  ink    x 42..214, y 10..246: a margin of 10 above and below

Outputs (committed; the format of boswas-os-mark.svg is a contract that
desktop/icons/tools/build_prism.py relies on):

  desktop/branding/boswas-os-mark.svg        full colour: viewBox 0 0 256 256,
                                             a <defs> of linear and radial
                                             gradients in user space, then
                                             <path> elements only (d, fill,
                                             path data in absolute M, L, C, Z)
  desktop/branding/boswas-os-mark-mono.svg   the same shapes in white, for
                                             recolouring with data-fill
                                             (build/scripts/inline-svg.py)
  desktop/branding/boswas-os-mark-flat.svg   the same shapes in solid colours,
                                             for small sizes
  control-plane/dashboard/favicon.svg        the flat mark on a dark tile,
                                             with no references (the
                                             dashboard's tests forbid href
                                             and url())

Usage (from anywhere; Python 3 standard library only, deterministic):

  python3 desktop/branding/tools/build_mark.py                # rewrite in place
  python3 desktop/branding/tools/build_mark.py --check        # fail if stale
  python3 desktop/branding/tools/build_mark.py --output DIR   # write to DIR
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

BRANDING = Path(__file__).resolve().parents[1]
REPO = BRANDING.parents[1]
TOKENS = REPO / "desktop" / "ui" / "tokens.json"
NOTICE = "Generated by desktop/branding/tools/build_mark.py from desktop/ui/tokens.json; do not edit by hand."

# --------------------------------------------------------------------------
# Construction
# --------------------------------------------------------------------------
VIEW = 256.0
TOP, BASE = 10.0, 246.0            # ink from the top of the stem to the baseline
RADIUS = 86.0                      # outer radius of the bowl
BAND = 40.0                        # width of the bowl's band
STEM = 42.0                        # width of the stem
GAP = 10.0                         # clear space between the stem and the bowl
DOT = 18.0                         # radius of the dot
CX, CY = VIEW / 2, BASE - RADIUS   # centre of the bowl: its bottom sits on the baseline
STEM_X = CX - RADIUS               # the stem's left edge is the bowl's leftmost point
CUT = STEM_X + STEM + GAP          # the bowl is cut clear of the stem here
INNER = RADIUS - BAND
DOT_X = (CUT + CX + INNER) / 2     # centred in the open counter, from the cut to the band
GEOMETRY = {
    "view": VIEW, "top": TOP, "base": BASE, "stem": (STEM_X, TOP, STEM, BASE - TOP),
    "bowl": (CX, CY, RADIUS, INNER), "cut": CUT, "dot": (DOT_X, CY, DOT),
    "ink": (STEM_X, TOP, CX + RADIUS, BASE),
}

# Paint: token references. A gradient is a list of (offset, token[, opacity]).
SHADOW_DEPTH = 24.0                # how far the stem's shadow reaches across the bowl
PAINT = {
    "bowl": ("linear", [(0, "azure.400"), (0.5, "azure.500"), (1, "iris.600")]),
    "bowl-shadow": ("linear", [(0, "iris.700", 0.55), (1, "iris.700", 0)]),
    "bowl-sheen": ("linear", [(0, "white", 0.24), (1, "white", 0)]),
    "stem": ("linear", [(0, "sky.400"), (0.5, "azure.400"), (1, "azure.600")]),
    "stem-sheen": ("linear", [(0, "white", 0.3), (1, "white", 0)]),
    "dot": ("radial", [(0, "sun.300"), (0.6, "sun.400"), (1, "sun.500")]),
}
FLAT = {"bowl": "azure.500", "stem": "azure.400", "dot": "sun.400"}
TILE = "neutral.950"               # the favicon's tile: the boot screen's background


# --------------------------------------------------------------------------
# Path data: absolute M, L, C and Z only, so that any consumer can read it
# --------------------------------------------------------------------------
def num(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


class Path_:
    def __init__(self, x: float, y: float):
        self.parts = [f"M{num(x)} {num(y)}"]

    def line(self, x: float, y: float) -> "Path_":
        self.parts.append(f"L{num(x)} {num(y)}")
        return self

    def arc(self, cx: float, cy: float, r: float, start: float, end: float) -> "Path_":
        """A circular arc from angle start to end (radians; y down, so increasing is clockwise),
        as cubic Bezier segments of at most a quarter turn each."""
        count = max(1, math.ceil(abs(end - start) / (math.pi / 2) - 1e-9))
        step = (end - start) / count
        k = 4 / 3 * math.tan(step / 4)
        for i in range(count):
            a0, a1 = start + i * step, start + (i + 1) * step
            x0, y0 = cx + r * math.cos(a0), cy + r * math.sin(a0)
            x1, y1 = cx + r * math.cos(a1), cy + r * math.sin(a1)
            self.parts.append("C" + " ".join(num(v) for v in (
                x0 - k * r * math.sin(a0), y0 + k * r * math.cos(a0),
                x1 + k * r * math.sin(a1), y1 - k * r * math.cos(a1), x1, y1)))
        return self

    def close(self) -> str:
        return "".join(self.parts) + "Z"


def angle(cx: float, cy: float, x: float, y: float) -> float:
    return math.atan2(y - cy, x - cx)


def circle(cx: float, cy: float, r: float) -> str:
    return Path_(cx, cy - r).arc(cx, cy, r, -math.pi / 2, 1.5 * math.pi).close()


def stem_path() -> str:
    r = STEM / 2
    x0, x1 = STEM_X, STEM_X + STEM
    return (Path_(x0 + r, TOP).arc(x0 + r, TOP + r, r, -math.pi / 2, 0).line(x1, BASE - r)
            .arc(x0 + r, BASE - r, r, 0, math.pi).line(x0, TOP + r)
            .arc(x0 + r, TOP + r, r, math.pi, 1.5 * math.pi).close())


def bowl_path() -> str:
    """The band between the two circles, right of the cut: outer arc clockwise, inner arc back."""
    outer = math.sqrt(RADIUS ** 2 - (CUT - CX) ** 2)
    inner = math.sqrt(INNER ** 2 - (CUT - CX) ** 2)
    return (Path_(CUT, CY - outer)
            .arc(CX, CY, RADIUS, angle(CX, CY, CUT, CY - outer), angle(CX, CY, CUT, CY + outer))
            .line(CUT, CY + inner)
            .arc(CX, CY, INNER, angle(CX, CY, CUT, CY + inner), angle(CX, CY, CUT, CY - inner))
            .close())


# Where each gradient runs: light from the top left.
def gradient_geometry() -> dict[str, tuple]:
    reach = RADIUS * 0.7
    return {
        "bowl": (CX - reach, CY - reach, CX + reach, CY + reach),
        "bowl-shadow": (CUT, CY, CUT + SHADOW_DEPTH, CY),
        "bowl-sheen": (CX, CY - RADIUS, CX, CY),
        "stem": (STEM_X, TOP, STEM_X + STEM, BASE),
        "stem-sheen": (STEM_X, TOP, STEM_X, TOP + 110),
        "dot": (DOT_X - 0.45 * DOT, CY - 0.45 * DOT, 1.55 * DOT),
    }


# The layers, back to front: (shape, paint, flat colour or None for an overlay).
def layers() -> list[tuple[str, str, str | None]]:
    bowl, stem = bowl_path(), stem_path()
    return [(bowl, "bowl", FLAT["bowl"]), (bowl, "bowl-shadow", None), (bowl, "bowl-sheen", None),
            (stem, "stem", FLAT["stem"]), (stem, "stem-sheen", None),
            (circle(DOT_X, CY, DOT), "dot", FLAT["dot"])]


# --------------------------------------------------------------------------
# Tokens
# --------------------------------------------------------------------------
def load_tokens(path: Path = TOKENS) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def colour(tokens: dict, ref: str) -> str:
    family, _, shade = ref.partition(".")
    value = tokens["color"][family][shade] if shade else tokens["color"][family]
    if not (isinstance(value, str) and len(value) == 7 and value.startswith("#")):
        raise SystemExit(f"tokens.json: color {ref} is not #RRGGBB: {value!r}")
    return value.upper()


def palette(tokens: dict) -> set[str]:
    """Every colour of the token palette (color.*), as #RRGGBB."""
    out = set()
    for value in tokens["color"].values():
        for v in (value.values() if isinstance(value, dict) else [value]):
            if isinstance(v, str) and v.startswith("#"):
                out.add(v.upper())
    return out


# --------------------------------------------------------------------------
# SVG
# --------------------------------------------------------------------------
def gradient(tokens: dict, name: str) -> str:
    kind, stops = PAINT[name]
    geo = gradient_geometry()[name]
    gid = f"boswas-mark-{name}"
    if kind == "linear":
        head = (f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{num(geo[0])}" '
                f'y1="{num(geo[1])}" x2="{num(geo[2])}" y2="{num(geo[3])}">')
        tail = "</linearGradient>"
    else:
        head = (f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{num(geo[0])}" '
                f'cy="{num(geo[1])}" r="{num(geo[2])}">')
        tail = "</radialGradient>"
    lines = [f"    {head}"]
    for stop in stops:
        opacity = f' stop-opacity="{num(stop[2])}"' if len(stop) > 2 else ""
        lines.append(f'      <stop offset="{num(stop[0])}" stop-color="{colour(tokens, stop[1])}"{opacity}/>')
    lines.append(f"    {tail}")
    return "\n".join(lines)


def svg_open(description: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">\n'
            f"  <!-- {description} -->\n  <!-- {NOTICE} -->\n")


def mark_svg(tokens: dict, variant: str) -> str:
    """variant: "colour", "mono" or "flat"."""
    description = {
        "colour": "The Boswas OS mark, full colour.",
        "mono": "The Boswas OS mark in one colour (white), for recolouring.",
        "flat": "The Boswas OS mark in solid colours, for small sizes.",
    }[variant]
    out = [svg_open(description)]
    if variant == "colour":
        out.append("  <defs>\n" + "\n".join(gradient(tokens, name) for name in PAINT) + "\n  </defs>\n")
    for shape, paint, flat in layers():
        if variant == "colour":
            fill = f"url(#boswas-mark-{paint})"
        elif flat is None:
            continue                    # shading overlays are part of the colour mark only
        else:
            fill = "#FFFFFF" if variant == "mono" else colour(tokens, flat)
        out.append(f'  <path fill="{fill}" d="{shape}"/>\n')
    out.append("</svg>\n")
    return "".join(out)


def favicon_svg(tokens: dict) -> str:
    """The flat mark on a 64 x 64 tile; no references of any kind."""
    shapes = "".join(f'    <path fill="{colour(tokens, flat)}" d="{shape}"/>\n'
                     for shape, _, flat in layers() if flat is not None)
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="Boswas">\n'
            f"  <!-- {NOTICE} -->\n"
            f'  <rect width="64" height="64" rx="14" fill="{colour(tokens, TILE)}"/>\n'
            '  <svg x="6" y="6" width="52" height="52" viewBox="0 0 256 256">\n'
            f"{shapes}  </svg>\n</svg>\n")


def outputs(tokens: dict) -> dict[str, str]:
    """Relative path (from the repository root) -> content."""
    return {
        "desktop/branding/boswas-os-mark.svg": mark_svg(tokens, "colour"),
        "desktop/branding/boswas-os-mark-mono.svg": mark_svg(tokens, "mono"),
        "desktop/branding/boswas-os-mark-flat.svg": mark_svg(tokens, "flat"),
        "control-plane/dashboard/favicon.svg": favicon_svg(tokens),
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    root = REPO
    if "--output" in argv:
        index = argv.index("--output")
        if index + 1 >= len(argv):
            print("usage: build_mark.py [--check | --output DIR]", file=sys.stderr)
            return 2
        root = Path(argv[index + 1])
    stale = []
    for relative, content in outputs(load_tokens()).items():
        target = root / relative
        if check:
            if not target.is_file() or target.read_text(encoding="utf-8") != content:
                stale.append(relative)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {relative}")
    if stale:
        print("stale (re-run desktop/branding/tools/build_mark.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
