def run(mode: str, keys: str, **settings) -> Engine:
    engine = Engine(mode)
    if "angle" in settings:
        engine.set_angle(settings["angle"])
    if "bits" in settings:
        engine.set_word_size(settings["bits"])
    if "radix" in settings:
        engine.set_radix(settings["radix"])
    return engine.press_all(keys)


class TableTest(unittest.TestCase):
    def check(self, rows, mode, **settings):
        for keys, expected in rows:
            with self.subTest(mode=mode, keys=keys, **settings):
                self.assertEqual(run(mode, keys, **settings).display, expected)

    def test_standard(self):
        self.check(STANDARD_ROWS, STANDARD)

    def test_scientific(self):
        self.check(SCIENTIFIC_ROWS, SCIENTIFIC)

    def test_degrees(self):
        self.check(DEGREE_ROWS, SCIENTIFIC, angle="deg")

    def test_radians(self):
        self.check(RADIAN_ROWS, SCIENTIFIC, angle="rad")

    def test_gradians(self):
        self.check(GRADIAN_ROWS, SCIENTIFIC, angle="grad")

    def test_hyperbolic_in_every_angle_unit(self):
        for angle in ("deg", "rad", "grad"):
            self.check(HYPERBOLIC_ROWS, SCIENTIFIC, angle=angle)

    def test_programmer(self):
        for bits, radix, keys, expected in PROGRAMMER_ROWS:
            with self.subTest(bits=bits, radix=radix, keys=keys):
                self.assertEqual(run(PROGRAMMER, keys, bits=bits, radix=radix).display, expected)

    def test_expression_line(self):
        for mode, keys, expected in EXPRESSION_ROWS:
            with self.subTest(mode=mode, keys=keys):
                self.assertEqual(run(mode, keys).expression_text, expected)

    def test_the_table_is_large(self):
        total = (len(STANDARD_ROWS) + len(SCIENTIFIC_ROWS) + len(DEGREE_ROWS) + len(RADIAN_ROWS) + len(GRADIAN_ROWS)
                 + len(HYPERBOLIC_ROWS) + len(PROGRAMMER_ROWS) + len(EXPRESSION_ROWS))
        self.assertGreater(total, 600)
        keys = [row[0] for row in STANDARD_ROWS]
        self.assertEqual(len(keys), len(set(keys)), "a Standard row is listed twice")


