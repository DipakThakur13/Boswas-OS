//! Build-time asset preparation for the Boswas OS boot screen.
//!
//! Everything the daemon draws is prepared here, so that at boot it parses no
//! SVG, font or image file: the official mark, the BOSWAS OS wordmark and an
//! ASCII glyph atlas are rasterised once and embedded as plain bytes, and the
//! colours are read from the Boswas UI token file.
//!
//! Sources (repository root is two levels up; the staged package build tree
//! keeps this layout):
//!   desktop/branding/boswas-os-mark.svg        the mark, full colour
//!   desktop/branding/wordmark-boswas-os.svg    the wordmark, white outlines
//!   desktop/fonts/orbitron/static/Orbitron-Medium.ttf   (SIL OFL 1.1)
//!   desktop/ui/tokens.json                     Boswas UI design tokens

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use resvg::tiny_skia;
use resvg::usvg;

/// Height of the embedded mark; the largest size the layout ever asks for.
const MARK_HEIGHT: u32 = 448;
/// Width of the embedded wordmark.
const WORDMARK_WIDTH: u32 = 1024;
/// Pixel size the glyph atlas is rasterised at (scaled down at run time).
const GLYPH_PX: f32 = 64.0;
const FIRST_CHAR: u8 = 0x20;
const LAST_CHAR: u8 = 0x7e;

/// Token colours the boot screen uses: (Rust constant, token path).
const COLOURS: &[(&str, &str)] = &[
    ("BACKGROUND", "ink.950"),
    ("FIELD_FILL", "ink.800"),
    ("TRACK", "ink.700"),
    ("FIELD_BORDER", "ink.600"),
    ("TEXT", "cloud.50"),
    ("TEXT_SECONDARY", "cloud.200"),
    ("TEXT_MUTED", "cloud.400"),
    ("ACCENT", "iris.400"),
    ("ACCENT_DEEP", "iris.600"),
    ("ACCENT_TAIL", "azure.400"),
    ("DANGER", "coral.400"),
    ("WARNING", "sun.400"),
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let desktop = manifest.join("../../desktop");
    let mark_svg = desktop.join("branding/boswas-os-mark.svg");
    let wordmark_svg = desktop.join("branding/wordmark-boswas-os.svg");
    let font_ttf = desktop.join("fonts/orbitron/static/Orbitron-Medium.ttf");
    let tokens_json = desktop.join("ui/tokens.json");
    for path in [&mark_svg, &wordmark_svg, &font_ttf, &tokens_json] {
        println!("cargo:rerun-if-changed={}", path.display());
    }
    println!("cargo:rerun-if-changed=build.rs");

    let mut code = String::from("// Generated by build.rs; do not edit.\n\n");

    // Colours.
    let tokens: serde_json::Value =
        serde_json::from_str(&read_text(&tokens_json)).expect("desktop/ui/tokens.json is not valid JSON");
    for (name, token) in COLOURS {
        let (r, g, b) = token_colour(&tokens, token);
        writeln!(code, "/// Boswas UI token `{token}`.\npub const {name}: Rgb = Rgb::new({r}, {g}, {b});").unwrap();
    }

    // The mark: premultiplied RGBA.
    let mark = rasterise(&mark_svg, None, Some(MARK_HEIGHT));
    fs::write(out.join("mark.rgba"), mark.data()).expect("write mark.rgba");
    writeln!(
        code,
        "\n/// The official Boswas OS mark, premultiplied RGBA8.\n\
         pub const MARK_WIDTH: u32 = {};\npub const MARK_HEIGHT: u32 = {};\n\
         pub static MARK_RGBA: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/mark.rgba\"));",
        mark.width(),
        mark.height()
    )
    .unwrap();

    // The wordmark: coverage only (it is tinted at run time).
    let wordmark = rasterise(&wordmark_svg, Some(WORDMARK_WIDTH), None);
    let alpha: Vec<u8> = wordmark.data().chunks_exact(4).map(|p| p[3]).collect();
    fs::write(out.join("wordmark.a8"), &alpha).expect("write wordmark.a8");
    writeln!(
        code,
        "\n/// The BOSWAS OS wordmark, 8-bit coverage.\n\
         pub const WORDMARK_WIDTH: u32 = {};\npub const WORDMARK_HEIGHT: u32 = {};\n\
         pub static WORDMARK_A8: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/wordmark.a8\"));",
        wordmark.width(),
        wordmark.height()
    )
    .unwrap();

    // Glyph atlas: printable ASCII from Orbitron Medium.
    let font_bytes = fs::read(&font_ttf).unwrap_or_else(|e| panic!("{}: {e}", font_ttf.display()));
    let font = fontdue::Font::from_bytes(font_bytes, fontdue::FontSettings::default()).expect("Orbitron-Medium.ttf");
    let line = font.horizontal_line_metrics(GLYPH_PX).expect("horizontal line metrics");
    let mut blob: Vec<u8> = Vec::new();
    let mut table = String::new();
    for ch in FIRST_CHAR..=LAST_CHAR {
        let (metrics, bitmap) = font.rasterize(ch as char, GLYPH_PX);
        assert_eq!(bitmap.len(), metrics.width * metrics.height);
        writeln!(
            table,
            "    Glyph {{ offset: {}, width: {}, height: {}, left: {}, bottom: {}, advance: {:.4} }},",
            blob.len(),
            metrics.width,
            metrics.height,
            metrics.xmin,
            metrics.ymin,
            metrics.advance_width
        )
        .unwrap();
        blob.extend_from_slice(&bitmap);
    }
    fs::write(out.join("glyphs.a8"), &blob).expect("write glyphs.a8");
    writeln!(
        code,
        "\n/// Glyph atlas: printable ASCII of Orbitron Medium (SIL OFL 1.1) at {GLYPH_PX} px.\n\
         pub const GLYPH_PX: f32 = {GLYPH_PX:.1};\npub const GLYPH_FIRST: u8 = {FIRST_CHAR};\n\
         pub const GLYPH_LAST: u8 = {LAST_CHAR};\npub const GLYPH_ASCENT: f32 = {:.4};\n\
         pub const GLYPH_DESCENT: f32 = {:.4};\n\
         pub static GLYPH_A8: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/glyphs.a8\"));\n\
         pub static GLYPHS: [Glyph; {}] = [\n{table}];",
        line.ascent,
        line.descent,
        (LAST_CHAR - FIRST_CHAR + 1)
    )
    .unwrap();

    fs::write(out.join("assets.rs"), code).expect("write assets.rs");
}

fn read_text(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

/// Resolve `family.shade` (for example `ink.950`) in the token file.
fn token_colour(tokens: &serde_json::Value, token: &str) -> (u8, u8, u8) {
    let (family, shade) = token.split_once('.').unwrap_or_else(|| panic!("bad token name {token}"));
    let hex = tokens["color"][family][shade]
        .as_str()
        .unwrap_or_else(|| panic!("token {token} is missing from desktop/ui/tokens.json"));
    let hex = hex.strip_prefix('#').unwrap_or_else(|| panic!("token {token} is not #RRGGBB: {hex}"));
    assert!(hex.len() == 6 && hex.is_ascii(), "token {token} is not #RRGGBB: {hex}");
    let channel = |i: usize| u8::from_str_radix(&hex[i..i + 2], 16).unwrap_or_else(|_| panic!("token {token}: {hex}"));
    (channel(0), channel(2), channel(4))
}

/// Render an SVG to a pixmap of the given width or height (aspect kept).
fn rasterise(path: &Path, width: Option<u32>, height: Option<u32>) -> tiny_skia::Pixmap {
    let tree = usvg::Tree::from_str(&read_text(path), &usvg::Options::default())
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let size = tree.size();
    let scale = match (width, height) {
        (Some(w), _) => w as f32 / size.width(),
        (None, Some(h)) => h as f32 / size.height(),
        (None, None) => 1.0,
    };
    let w = (size.width() * scale).round().max(1.0) as u32;
    let h = (size.height() * scale).round().max(1.0) as u32;
    let mut pixmap = tiny_skia::Pixmap::new(w, h).expect("pixmap");
    let transform = tiny_skia::Transform::from_scale(w as f32 / size.width(), h as f32 / size.height());
    resvg::render(&tree, transform, &mut pixmap.as_mut());
    pixmap
}
