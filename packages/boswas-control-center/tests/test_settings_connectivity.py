class NetinfoTest(unittest.TestCase):
    def details(self) -> netinfo.Details:
        interfaces = netinfo.combine(netinfo.parse_addresses(IP_ADDR), netinfo.parse_gateways(IP_ROUTE4),
                                     netinfo.parse_gateways(IP_ROUTE6), {"enp3s0": 1000, "wlp2s0": None},
                                     {"wlp2s0"})
        dns, search = netinfo.parse_resolv_conf(RESOLV)
        return netinfo.Details(interfaces, dns, search)

    def test_realistic_documents(self):
        details = self.details()
        self.assertEqual([i.name for i in details.interfaces], ["enp3s0", "wlp2s0"])      # no loopback, no tunnel
        wired, wifi = details.interfaces
        self.assertEqual((wired.kind, wired.connected, wired.mac), ("Ethernet", True, "3c:52:82:aa:bb:01"))
        self.assertEqual(wired.ipv4, ("192.168.1.23/24",))
        self.assertEqual(wired.ipv6, ("2001:db8::23/64", "fe80::3e52:82ff:feaa:bb01/64"))
        self.assertEqual((wired.gateway4, wired.gateway6), ("192.168.1.1", "fe80::1"))    # the lowest metric wins
        self.assertEqual(wired.speed, 1000)
        self.assertEqual((wifi.kind, wifi.connected, wifi.speed), ("Wi-Fi", False, None))
        self.assertEqual(details.dns, ("192.168.1.1", "2001:db8::53"))
        self.assertEqual(details.search, ("example.org", "lan"))
        rows = dict(netinfo.interface_rows(wired, details))
        self.assertEqual(rows, {"Status": "Connected", "IPv4 address": "192.168.1.23/24",
                                "IPv4 gateway": "192.168.1.1",
                                "IPv6 address": "2001:db8::23/64, fe80::3e52:82ff:feaa:bb01/64",
                                "IPv6 gateway": "fe80::1", "DNS servers": "192.168.1.1, 2001:db8::53",
                                "Search domains": "example.org, lan", "Physical address (MAC)": "3c:52:82:aa:bb:01",
                                "Link speed": "1 Gb/s"})
        self.assertEqual(dict(netinfo.interface_rows(wifi, details)),
                         {"Status": "Not connected", "Physical address (MAC)": "a0:b1:c2:d3:e4:f5"})
        text = netinfo.details_text(details)
        self.assertIn("Ethernet (enp3s0)\n  Status: Connected\n  IPv4 address: 192.168.1.23/24", text)
        self.assertIn("Wi-Fi (wlp2s0)", text)

    def test_hostile_documents(self):
        for text in (None, 5, "", "not json", "{}", "[1, 2]", '"x"', "[" * 10000, json.dumps({"ifname": "eth0"})):
            self.assertEqual(netinfo.parse_addresses(text), [], repr(text)[:30])
            self.assertEqual(netinfo.parse_gateways(text), {}, repr(text)[:30])
        bad = json.dumps([
            {"ifname": "../../etc", "link_type": "ether"}, {"ifname": "eth0; rm", "link_type": "ether"},
            {"ifname": 5, "link_type": "ether"}, {"ifname": "x" * 40, "link_type": "ether"},
            {"ifname": "eth1", "link_type": "ether", "address": "<b>mac</b>", "flags": "UP", "addr_info": "x"},
            {"ifname": "eth2", "link_type": "ether", "operstate": "UP", "addr_info": [
                None, {"family": "inet", "local": "999.1.1.1", "prefixlen": 24},
                {"family": "inet", "local": "10.0.0.1", "prefixlen": 99999},
                {"family": "inet", "local": "10.0.0.2", "prefixlen": True},
                {"family": "inet", "local": "<script>", "prefixlen": 8},
                {"family": "inet6", "local": "fe80::1%eth2", "prefixlen": 64},
                {"family": "inet", "local": "10.0.0.3", "prefixlen": 8}]}])
        found = netinfo.parse_addresses(bad)
        self.assertEqual([i.name for i in found], ["eth1", "eth2"])
        self.assertEqual(found[0].mac, "")
        self.assertEqual((found[1].ipv4, found[1].ipv6), (("10.0.0.3/8",), ("fe80::1/64",)))
        routes = json.dumps([{"dst": "default", "gateway": "evil", "dev": "eth0"},
                             {"dst": "default", "gateway": "10.0.0.1", "dev": "../x"},
                             {"dst": "default", "dev": "eth0"}, {"dst": "default", "gateway": "10.0.0.1", "dev": 5},
                             {"dst": "default", "gateway": "10.0.0.9", "dev": "eth0", "metric": "low"}])
        self.assertEqual(netinfo.parse_gateways(routes), {"eth0": "10.0.0.9"})
        many = json.dumps([{"ifname": f"eth{i}", "link_type": "ether"} for i in range(500)])
        self.assertEqual(len(netinfo.parse_addresses(many)), netinfo.MAX_INTERFACES)
        self.assertEqual(netinfo.parse_resolv_conf(None), ((), ()))
        servers, search = netinfo.parse_resolv_conf("nameserver\nnameserver 1.1.1.1 ; x\nsearch a/b ok.example\n"
                                                    + "nameserver 10.0.0.%d\n" * 20 % tuple(range(20)))
        self.assertEqual(len(servers), netinfo.MAX_DNS)
        self.assertEqual(search, ("ok.example",))
        for text in ("-1", "", "fast", None, "0", "99999999"):
            self.assertIsNone(netinfo.parse_speed(text))
        self.assertEqual(netinfo.parse_speed("2500\n"), 2500)
        self.assertEqual([netinfo.speed_text(s) for s in (None, 100, 1000, 2500)], ["", "100 Mb/s", "1 Gb/s",
                                                                                   "2.5 Gb/s"])

    def test_read_uses_only_the_three_queries(self):
        from boswas_control_center import commands
        ran = []

        class Runner:
            def run(self, command, timeout):
                ran.append(command)
                return commands.Completed(0, {"addr": IP_ADDR, "-4": IP_ROUTE4, "-6": IP_ROUTE6}[command[2]], "")

        with __import__("tempfile").TemporaryDirectory() as root:
            fx.write(Path(root) / "etc/resolv.conf", RESOLV)
            fx.write(Path(root) / "sys/class/net/enp3s0/speed", "2500\n")
            fx.write(Path(root) / "sys/class/net/enp3s0/uevent", "INTERFACE=enp3s0\nIFINDEX=2\n")
            fx.write(Path(root) / "sys/class/net/wlp2s0/uevent", "DEVTYPE=wlan\nINTERFACE=wlp2s0\n")
            details = netinfo.read(Runner(), commands.argv, root)
        self.assertEqual([c[1:] for c in ran], [["-j", "addr", "show"], ["-j", "-4", "route", "show"],
                                                ["-j", "-6", "route", "show"]])
        self.assertEqual(details.interfaces[0].speed, 2500)
        self.assertEqual(details.interfaces[1].kind, "Wi-Fi")
        self.assertEqual(details.dns, ("192.168.1.1", "2001:db8::53"))

    def test_proxy_settings_hide_passwords(self):
        env = {"http_proxy": "http://alice:s3cret@proxy.example:3128/", "HTTPS_PROXY": "http://proxy.example:3128",
               "https_proxy": "", "no_proxy": "localhost,127.0.0.1,.example.org", "ALL_PROXY": "socks5://bob@10.0.0.1",
               "ftp_proxy": "   "}
        rows = dict(netinfo.proxy_settings(env))
        self.assertEqual(rows, {"HTTP proxy": "http://alice:***@proxy.example:3128/",
                                "HTTPS proxy": "http://proxy.example:3128",
                                "Proxy for everything else": "socks5://bob@10.0.0.1",
                                "No proxy for": "localhost,127.0.0.1,.example.org"})
        self.assertNotIn("s3cret", repr(rows))
        self.assertEqual(netinfo.proxy_settings({}), [])
        self.assertEqual(netinfo.mask_proxy("user:pw@host:8080"), "user:***@host:8080")
        self.assertEqual(netinfo.mask_proxy("http://host/path@x"), "http://host/path@x")
        self.assertEqual(netinfo.mask_proxy("http://u:p\x1b[0m@h\n"), "http://u:***@h")


